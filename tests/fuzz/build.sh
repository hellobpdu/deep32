# Builds the fuzz targets in tests/fuzz on Linux. Each target compiles its harness (targets/TARGET.c) together with
# the C sources it tests, read in place under src/workstation; nothing there is copied or changed.
#
#   sh tests/fuzz/build.sh [fuzz|replay|all] [TARGET...]
#
#   fuzz    OUT/fuzz-TARGET: libFuzzer with AddressSanitizer and UndefinedBehaviorSanitizer (needs clang)
#   replay  OUT/replay-TARGET: the same harness with replay.c in place of libFuzzer, run once per input file
#           (clang or gcc)
#   all     both (the default)
#
# With no TARGET every target is built. OUT defaults to tests/fuzz/out. CC picks the compiler; by default the
# first of clang, clang-21 ... clang-14 found on PATH. Assertions stay on: NDEBUG is never defined, and an
# undefined-behavior report stops the program like a memory error does.
#
# Findings: the five defects the fuzzers found (README.md, section "Findings", F-1 to F-5) are fixed in the
# Library's readers, so the default build has no exceptions left and FUZZ_STRICT=1 builds the same thing. known()
# stays as the place for a check that a future finding must leave out until its release; the seed-finding-* inputs
# in corpus/ are now regression inputs that every build replays.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
out=${OUT:-$here/out}
strict=${FUZZ_STRICT:-0}
W=$root/src/workstation
L=$W/library/src
A=$W/node/asklink
N=$W/ship/u10/src/netaddr

TARGETS="appjson asklink b64 d32json d32vec d32ww dib e26j e26p imgscale json8 kwaj netaddr pnm rfctext text8 wav"

# The sources a target tests, compiled in place.
sources() {
	case $1 in
	appjson) echo "$L/app/json.c" ;;
	asklink) echo "$A/src/frame.c $A/src/json.c $A/src/msg.c $A/src/util.c $A/src/sas.c $out/gen/bip39.c" \
		"$here/shims/openbsd.c $L/common/sha256.c" ;;
	b64) echo "$L/common/b64.c" ;;
	d32json) echo "$W/ship/u10/src/lib/core/d32_json.c" ;;
	d32vec) echo "$W/node/d32vec.c" ;;
	d32ww) echo "$L/common/d32ww.c" ;;
	dib) echo "$L/import/dib.c $L/common/image.c $L/common/sha256.c" ;;
	e26j) echo "$L/common/e26j.c $L/app/json.c" ;;
	e26p) echo "$L/common/e26p.c" ;;
	imgscale) echo "$L/common/imgscale.c" ;;
	json8) echo "$L/common/json8.c $L/app/json.c" ;;
	kwaj) echo "$L/import/kwaj.c" ;;
	netaddr) echo "$N/netaddr.c $N/nettext.c $N/netpolicy.c $N/netplan.c" ;;
	pnm) echo "$L/common/image.c $L/common/sha256.c" ;;
	rfctext) echo "$L/common/rfctext.c" ;;
	text8) echo "$L/common/text8.c" ;;
	wav) echo "$L/import/wav.c" ;;
	*) return 1 ;;
	esac
}

# Language level and defines as each component's own makefile has them, and the include paths.
cflags() {
	case $1 in
	asklink) echo "-std=c99 -D_DEFAULT_SOURCE -include $here/shims/openbsd.h -I$here/shims -I$A/src -I$L/common" ;;
	d32json) echo "-std=gnu99 -I$W/ship/u10/src/lib/core" ;;
	d32vec) echo "-std=c99 -ffp-contract=off" ;;
	netaddr) echo "-std=c99 -I$N" ;;
	*) echo "-std=c99 -D_POSIX_C_SOURCE=200809L -D_DEFAULT_SOURCE -I$L" ;;
	esac
}

# The checks left out for one source file while its findings wait for a release (see the header). None at present:
# it prints nothing for every file. AddressSanitizer stays on.
known() {
	[ "$strict" = 1 ] && return 0
	case $1 in
	*) ;;
	esac
}

if [ -z "${CC:-}" ]; then
	for c in clang clang-21 clang-20 clang-19 clang-18 clang-17 clang-16 clang-15 clang-14; do
		if command -v "$c" >/dev/null 2>&1; then CC=$c; break; fi
	done
fi
if [ -z "${CC:-}" ]; then
	echo "build.sh: no clang found; install clang (and libclang-rt-dev on Debian or Ubuntu), or set CC" >&2
	exit 1
fi

mode=all
case ${1:-} in
fuzz|replay|all) mode=$1; shift ;;
esac
want=${*:-$TARGETS}
for t in $want; do
	sources "$t" >/dev/null || { echo "build.sh: unknown target $t (known: $TARGETS)" >&2; exit 2; }
done

COMMON="-g -O1 -fno-omit-frame-pointer -UNDEBUG -fno-sanitize-recover=all -Wall -Wextra -I$here"
[ "$strict" = 1 ] && COMMON="$COMMON -DFUZZ_STRICT"
mkdir -p "$out/gen"

# The Ask link's word list source, generated as node/asklink/gen-bip39.sh does it (with the same SHA-256 pin).
bip39() {
	f=$A/vendor/bip39-english.txt
	pin=2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda
	got=$(sha256sum "$f" | cut -d ' ' -f 1)
	[ "$got" = "$pin" ] || { echo "build.sh: $f does not match its SHA-256 pin" >&2; exit 1; }
	[ "$(wc -l < "$f" | tr -d ' ')" = 2048 ] || { echo "build.sh: $f is not 2048 lines" >&2; exit 1; }
	{
		echo "/* Generated by tests/fuzz/build.sh from node/asklink/vendor/bip39-english.txt. */"
		echo '#include "d32u.h"'
		echo 'const char *const bip39_words[2048] = {'
		awk '{ printf "\t\"%s\",\n", $1 }' "$f"
		echo '};'
	} > "$out/gen/bip39.c.tmp"
	mv "$out/gen/bip39.c.tmp" "$out/gen/bip39.c"
}

# link KIND TARGET COMPILE-SANITIZERS LINK-SANITIZERS EXTRA-SOURCE...: one object per source, then the program
link() {
	kind=$1 t=$2 csan=$3 lsan=$4
	shift 4
	obj=$out/obj/$kind-$t
	rm -rf "$obj"
	mkdir -p "$obj"
	i=0
	objs=""
	for src in "$here/targets/$t.c" "$@" $(sources "$t"); do
		i=$((i + 1))
		o=$obj/$i-$(basename "$src" .c).o
		# shellcheck disable=SC2046,SC2086 # the flag lists are meant to split into words
		$CC $COMMON $(cflags "$t") "$csan" $(known "$src") -c "$src" -o "$o"
		objs="$objs $o"
	done
	# shellcheck disable=SC2086
	$CC "$lsan" $objs -o "$out/$kind-$t" -lm
	echo "build.sh: $out/$kind-$t"
}

echo "build.sh: $("$CC" --version | head -n 1)$([ "$strict" = 1 ] && echo ", FUZZ_STRICT=1")"
for t in $want; do
	[ "$t" = asklink ] && bip39
	if [ "$mode" != replay ]; then
		link fuzz "$t" -fsanitize=fuzzer-no-link,address,undefined -fsanitize=fuzzer,address,undefined
	fi
	if [ "$mode" != fuzz ]; then
		link replay "$t" -fsanitize=address,undefined -fsanitize=address,undefined "$here/replay.c"
	fi
done
