def rows(path):
    for line in path.read_text(encoding='utf-8').splitlines():
        if line.strip() and not line.startswith('#'):
            yield [('' if f == '-' else f) for f in line.split('\t')]


def load(data):
    hv = dict(hv=[], field=[], step=[], rule=[], fact={}, fix=[], text={})
    for r in rows(data / HV_FILE):
        kind = r[0]
        if kind == 'hv':
            hv['hv'].append(dict(id=r[1], name=r[2], tested=r[3], here=r[4], local=r[5], nets=r[7]))
        elif kind == 'field':
            hv['field'].append(dict(hv=r[1], where=r[2], label=r[4], default=r[5], help=r[8]))
        elif kind == 'step':
            hv['step'].append(dict(hv=r[1], where=r[2], net=r[3], os=r[4], id=r[5], check=r[6], title=r[7],
                                   place=r[8], body=r[9], look=r[10] if len(r) > 10 else ''))
        elif kind == 'rule':
            hv['rule'].append(dict(hv=r[1], phase=r[2], fact=r[3], op=r[4], value=r[5], code=r[6]))
        elif kind == 'fact':
            hv['fact'][r[1]] = r[2]
        elif kind == 'fix':
            hv['fix'].append(dict(hv=r[1], code=r[2], steps=r[3]))
        elif kind == 'text':
            hv['text'][r[1]] = r[2]
    errors = [dict(kind=r[0], key=r[1], os=r[2], source=r[3], meaning=r[4], fix=r[5]) for r in rows(data / ERR_FILE)]
    return hv, errors


def items(text):
    return [part.strip() for part in text.split(' | ') if part.strip()]


def numbered(steps):
    return '\n'.join(f'{n}. {s}' for n, s in enumerate(steps, 1))


def hypervisor_page(hv, errors, h):
    hid, text = h['id'], hv['text']
    tested = 'boot-tested' if h['tested'] == 'yes' else 'not boot-tested yet'
    out = [HEAD + f'# Workstation VM guide: {h["name"]} ({tested})', '', text.get(f'hv-{hid}', ''), '',
           'Values in braces, such as {vmid} or {vm}, are what the person typed on the settings screen. The wizard '
           'shows every command with those values filled in. Read the commands from the person\'s screen or from the '
           f'steps file, `steps-{hid}.txt` in the kit folder, and never change them.', '',
           '## Screens before the steps', '',
           f'1. **Which hypervisor runs the Workstation VM?** The person picks "{h["name"]}". The list says "{tested}".',
           f'2. **Where does the VM run?** {WHERE_SCREEN[h["here"]]}']
    nets = h['nets'].split(',')
    if len(nets) == 1:
        only = text.get(f'net-{hid}-only') or text['net-only'].replace('{hvname}', h['name'])
        out.append(f'3. **The network.** No choice here: "{only}"')
    else:
        choices = '; '.join(f'{text["net-label-" + n]}: {text[f"net-{hid}-{n}"]}' for n in nets)
        out.append(f'3. **The network.** Two choices: {choices}. Bridged is marked "recommended". NAT also works.')
    out += ['4. **Tailscale, here and across sites.** A note only. Continue.',
            '5. **The VM\'s settings.** Enter keeps the value in brackets:', '',
            '| Field | Default | What it is |', '|---|---|---|']
    for f in hv['field']:
        if f['hv'] in ('*', hid):
            label = f['label'] + (f' ({TAGS[f["where"]]} only)' if f['where'] in TAGS else '')
            out.append(f'| {label} | {DEFAULTS.get(f["default"], f["default"]) or "(empty)"} | {f["help"]} |')
    out.append('')
    if hid == 'proxmox':
        out += ['The API token is optional. If the person types a token name, the wizard later shows the node\'s '
                'certificate fingerprint ("Does it match? [y/N]") and asks for the token\'s secret. The person types '
                'the secret into the wizard. The agent never asks for it and never sees it.', '']
    if h['local']:
        out.append(f'Read-only tool the wizard uses to check the VM: {TOOL[h["local"]]}.')
    else:
        out.append('The wizard has no read-only tool for this hypervisor. Every VM step is a "you confirm" step.')
    out += ['', '## The steps', '']
    order = []
    for s in hv['step']:
        if s['hv'] == hid and s['id'] not in order:
            order.append(s['id'])
    for n, sid in enumerate(order, 1):
        variants = [s for s in hv['step'] if s['hv'] == hid and s['id'] == sid]
        out += [f'### Step {n}: {variants[0]["title"]}', '']
        for s in variants:
            if len(variants) > 1:
                tags = [TAGS[t] for t in (s['where'], s['net'], s['os']) if t in TAGS]
                out += [f'**For: {", ".join(tags)}**', '']
            out += [f'Where: {s["place"]}', '', 'On screen, in order:', '',
                    numbered(items(s['body'].replace('{ts-stall}', text['ts-stall']))), '',
                    'What the wizard does on Enter: ' + CHECK[s['check']], '']
            if s['look']:
                out += [f'Look for: {s["look"]}', '']
    read = set(FACTS_READ.get(hid, '').split())
    for phase, after in (('create', 'after "Create the VM"'), ('after', 'after "Boot the installed disk; attach disc 2"')):
        own = {r['fact'] for r in hv['rule'] if r['hv'] == hid and r['phase'] == phase}
        rules = [r for r in hv['rule'] if r['phase'] == phase and r['fact'] in read and
                 (r['hv'] == hid or (r['hv'] == '*' and r['fact'] not in own))]
        if not rules:
            continue
        out += [f'## Checks {after}', '',
                'The wizard applies a check only when it could read that setting. A failed check shows '
                '"Result: ERROR CODE" with "What it means" and "What to do".', '',
                '| Setting | Must be | Code if not |', '|---|---|---|']
        for r in rules:
            value = r['value'].replace(',', ', ') + (' bytes (200 GB)' if r['fact'] == 'target_bytes' else '')
            out.append(f'| {hv["fact"][r["fact"]]} | {OPS[r["op"]]} {value} | {r["code"]} |')
        out.append('')
    fixes = [f for f in hv['fix'] if f['hv'] == hid]
    if fixes:
        out += ['## Fixes the wizard shows for this hypervisor', '',
                'These replace the general fix in errors.md for the same code.', '']
        for f in fixes:
            meaning = next((e['meaning'] for e in errors if e['kind'] == 'code' and e['key'] == f['code']), '')
            out += [f'**{f["code"]}**' + (f': {meaning}' if meaning else ''), '', numbered(items(f['steps'])), '']
    return '\n'.join(out).rstrip() + '\n'


def errors_page(errors):
    out = [HEAD + '# Error codes and what to do', '',
           'The wizard explains every failure with a row of `install/deep32-wizard-errors.tsv`. The full screen shows '
           'the row as "What it means" and "What to do". This file holds two parts of that table: the exit statuses '
           'and the VM guide\'s codes. Look up any other code in the table itself, as below.', '',
           '## Look up a code', '',
           'Run one of these from the repository folder. Put the exact code or a short exact piece of the line in '
           'place of CODE.', '',
           '```sh\ngrep -n -F -- \'CODE\' install/deep32-wizard-errors.tsv\n```', '',
           '```powershell\nSelect-String -SimpleMatch -Path install\\deep32-wizard-errors.tsv -Pattern \'CODE\'\n```', '',
           'Each row has six fields separated by a TAB: kind (exit, code or text), key, os (any, linux, windows or '
           'macos), source (the tool that prints it), meaning, and fix. The fix is up to five steps separated by " | "; '
           'text in backticks is a command. Use the row whose os matches the machine; otherwise the "any" row. A '
           '"text" row\'s key is a pattern for a whole output line, so search for a short exact piece of the line. '
           'Tell the person the meaning and the steps word for word.', '',
           '## Exit statuses', '',
           'The key is TOOL:STATUS. The full screen shows them under "What the tools said", for example '
           '"deep32-get exit 10".', '']
    for title, picked in (('', [e for e in errors if e['kind'] == 'exit']),
                          ('## VM guide codes', [e for e in errors if e['kind'] == 'code' and e['source'] == 'wizard'])):
        if title:
            out += [title, '', 'A VM step shows "Result: ERROR CODE". The hypervisor file may hold a fix of its own for '
                    'the same code; use that one first.', '']
        for e in picked:
            system = '' if e['os'] == 'any' else f' ({e["os"]})'
            out += [f'**{e["key"]}**{system}: {e["meaning"]}', '', numbered(items(e['fix'])), '']
    return '\n'.join(out).rstrip() + '\n'


def generated(data):
    hv, errors = load(data)
    pages = {'errors.md': errors_page(errors)}
    for h in hv['hv']:
        pages[f'hypervisors/{h["id"]}.md'] = hypervisor_page(hv, errors, h)
    return pages


def files(folder):
    return sorted(p.relative_to(folder).as_posix() for p in folder.rglob('*') if p.is_file())


def differ(name, expected, actual):
    diff = list(difflib.unified_diff(expected.splitlines(), actual.splitlines(), 'expected/' + name, name,
                                     lineterm='', n=0))
    return f'{name} differs ({len(diff)} diff lines):\n  ' + '\n  '.join(diff[:12])


def check(claude, codex, pages):
    problems = []
    names = sorted(pages) if pages is not None else sorted(n for n in files(claude) if n == 'errors.md' or
                                                            n.startswith('hypervisors/'))
    for agent, folder in (('claude', claude), ('codex', codex)):
        want = sorted(HAND + names + OWN[agent])
        have = files(folder)
        if have != want:
            problems.append(f'{agent} skill file set differs: extra {sorted(set(have) - set(want))}, '
                            f'missing {sorted(set(want) - set(have))}')
    for name in HAND + names:
        a, b = claude / name, codex / name
        if a.is_file() and b.is_file() and a.read_bytes() != b.read_bytes():
            problems.append(differ('codex ' + name, a.read_text(encoding='utf-8'), b.read_text(encoding='utf-8')))
    if pages is not None:
        for name, text in pages.items():
            if (claude / name).is_file() and (claude / name).read_text(encoding='utf-8') != text:
                problems.append(differ('claude ' + name, text, (claude / name).read_text(encoding='utf-8')))
    return problems


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    ap.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[2])
    ap.add_argument('--data', type=Path)
    try:
        args = ap.parse_args()
    except SystemExit:
        return 2
    claude = args.root / '.claude/skills/deep32-install'
    codex = args.root / '.agents/skills/deep32-install'
    data = args.data or args.root / 'install'
    if not (claude.is_dir() and codex.is_dir()):
        print(f'skill folder missing under {args.root}')
        return 2
    have_data = (data / HV_FILE).is_file() and (data / ERR_FILE).is_file()
    if args.write and not have_data:
        print(f'{HV_FILE} and {ERR_FILE} not found in {data}')
        return 2
    pages = generated(data) if have_data else None
    if args.write:
        for name in HAND:
            (codex / name).write_bytes((claude / name).read_bytes())
        for name, text in pages.items():
            for folder in (claude, codex):
                (folder / name).parent.mkdir(parents=True, exist_ok=True)
                (folder / name).write_bytes(text.encode('utf-8'))
        print(f'wrote {len(HAND)} copied and {len(pages)} generated files to both skills')
    if not have_data:
        print(f'wizard data not found in {data}: generated files compared between the two skills only')
    problems = check(claude, codex, pages)
    for p in problems:
        print('DRIFT: ' + p)
    print('install skills in step' if not problems else f'{len(problems)} difference(s)')
    return 0 if not problems else 1


if __name__ == '__main__':
    sys.exit(main())
