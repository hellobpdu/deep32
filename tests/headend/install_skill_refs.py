"""install_skill_refs.py: keeps the deep32-install skills' reference files in step with each other and the wizard data.

Two project skills drive the agent install: .claude/skills/deep32-install (Claude Code) and
.agents/skills/deep32-install (Codex). Each has its own SKILL.md; the Codex one also has agents/openai.yaml. Every other
file is the same in both:

- choose-setup.md, wizard-screens.md, vm-guide-screens.md, windows-forge.md, if-you-see.md, workstation-steps.md and
  setup-events.md are written by hand in the Claude skill and copied to the Codex skill unchanged;
- errors.md and hypervisors/<id>.md are generated from install/deep32-wizard-hv.tsv and
  install/deep32-wizard-errors.tsv, the two data files both setup wizards read. Every step, value, check, code and fix
  in them comes from a row of those files.

Usage:   python -I -B install_skill_refs.py --check [--root REPO] [--data DIR]   report drift, change nothing
         python -I -B install_skill_refs.py --write [--root REPO] [--data DIR]   regenerate and copy, then check
--data names the folder with the two .tsv files (default REPO/install). Without them, --check compares the generated
files between the two skills only and says so; --write refuses.
Exit:    0 in step; 1 drift found (each difference is printed); 2 bad arguments or a missing folder or data file.
"""
