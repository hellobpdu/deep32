"""Write a hash-pinned requirements file (pip --require-hashes) for a list of name==version pins.

Usage: python -I mklock.py PINLIST TAG DIR [DIR ...]  > requirements-x.lock
  PINLIST: lines "name==version  [anything after whitespace is ignored]", '#' comments allowed.
  TAG: the interpreter tag the wheels must fit (cp312, cp314) or "any" (pure wheels only).
  DIR: directories holding wheels (the wheelhouse, the verified PyPI download dir).
For each pin, every wheel in DIRs whose name and version match and whose tag is py3-none-any or TAG is hashed and
listed (one --hash per artefact). A pin with no matching wheel is an error (exit 1): the lock never falls back to
an sdist, so `pip install --no-index --require-hashes --only-binary :all:` installs exactly what was built.
Runs with any Python >= 3.9 (stdlib only), on the source workstation or the VM.
"""
import hashlib
import re
import sys
from pathlib import Path


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def main() -> int:
    pinlist, tag, *dirs = sys.argv[1:]
    wheels = []
    for d in dirs:
        for w in sorted(Path(d).glob("*.whl")):
            parts = w.name[:-4].split("-")
            name, version, pytag, abi, plat = norm(parts[0]), parts[1], parts[-3], parts[-2], parts[-1]
            fits = (abi == "none" and plat == "any") or pytag == tag
            wheels.append((name, version, fits, w))
    out, missing = [], []
    for line in Path(pinlist).read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        spec = line.split()[0]
        name, version = spec.split("==")
        name = norm(name)
        hits = {w.name: w for n, v, fits, w in wheels if n == name and v == version and fits}
        if not hits:
            missing.append(spec)
            continue
        hashes = sorted({hashlib.sha256(w.read_bytes()).hexdigest() for w in hits.values()})
        files = ", ".join(sorted(hits))
        out.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes)
                   + f"\n    # {files}")
    print(f"# generated by tools/mklock.py from {Path(pinlist).name} for {tag}; install with\n"
          f"#   pip install --no-index --only-binary :all: --require-hashes --find-links <wheelhouse> -r <this file>")
    print("\n".join(out))
    for m in missing:
        print(f"MISSING WHEEL {m}", file=sys.stderr)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
