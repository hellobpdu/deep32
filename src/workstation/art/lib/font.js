function makeFont(table, w, h, name) {
  return {
    name, w, h,
    glyph(ch) {
      const rows = table[ch] || table['?'];
      if (!table[ch]) throw new Error(`${name}: no glyph for '${ch}'`);
      return { w: rows.length ? rows[0].length : (ch === ' ' ? w - 2 : w), rows };
    },
    width(str, gap = 1) { let n = 0; for (const ch of str) n += this.glyph(ch).w + gap; return Math.max(0, n - gap); },
    has(ch) { return ch in table; },
  };
}

