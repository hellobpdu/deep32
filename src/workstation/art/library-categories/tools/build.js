#!/usr/bin/env node
'use strict';
// Builds every category's art into out/ (XPM for the engine, indexed PNG, Windows BMP), the contact sheet of our art,
// out/category-art.json (what the engine needs to load it) and out/MANIFEST.json (SHA-256 of every file).
//   node tools/build.js            write out/
//   node tools/build.js --check    rebuild in memory and compare byte for byte with out/MANIFEST.json
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { pngIndexed, bmp, xpm } = require('../lib/image');
const { Sheet } = require('../lib/sheet');
const cats = require('../src/categories');
const strips = require('../src/strips');
const font = require('../lib/font');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'out');
const check = process.argv.includes('--check');
const sha = b => crypto.createHash('sha256').update(b).digest('hex');

function build() {
  const files = new Map(); // rel path -> Buffer
  const put = (rel, buf) => files.set(rel, Buffer.isBuffer(buf) ? buf : Buffer.from(buf));
  const snap = cats.snapshot();
  const index = [];
  const built = [];
  for (const c of snap.categories) {
    const b = cats.build(c);
    built.push(b);
    const sets = [
      ['cat', c.id, b.cat_strip, 4, { frames: 2, frame: [strips.CAT.w, strips.CAT.h], states: ['normal', 'selected'] }],
      ['findwizard', c.id, b.fw_strip, 8, { frames: 4, frame: [strips.FW.w, strips.FW.h], states: ['normal', 'checked', 'pressed', 'disabled'] }],
      ['watermark', c.id, b.watermark, 4, { frames: 1, frame: [strips.WM.w, strips.WM.h], states: ['normal'] }],
      ['icon', `${c.id}.16`, b.icon16, 4, { frames: 1, frame: [16, 16], states: ['normal'] }],
      ['icon', `${c.id}.32`, b.icon32, 4, { frames: 1, frame: [32, 32], states: ['normal'] }],
    ];
    const entry = { id: c.id, order: c.order, menu: c.menu, label: c.label, bar_label: c.bar_label, face: c.face, ink: c.ink, emblem: c.emblem, watermark_motif: c.watermark, art: {} };
    for (const [dir, name, img, bpp, meta] of sets) {
      const base = `${dir}/${name}`;
      put(`${base}.xpm`, xpm(img, `${dir}_${name}`));
      put(`${base}.png`, pngIndexed(img));
      put(`${base}.bmp`, bmp(img, bpp));
      const key = dir === 'icon' ? `icon${name.split('.').pop()}` : dir;
      entry.art[key] = { xpm: `${base}.xpm`, png: `${base}.png`, bmp: `${base}.bmp`, size: [img.w, img.h], ...meta, palette: img.pal };
    }
    index.push(entry);
  }
  put('category-art.json', JSON.stringify({
    schema: 'deep32-d32library-category-art/1',
    taxonomy: { source: snap.source, sha256: snap.source_sha256, status: snap.source_status, date: snap.source_date },
    font: font.load(strips.FONT).props.FONT,
    geometry: { cat: strips.CAT, findwizard: strips.FW, watermark: strips.WM, motif: strips.MOTIF },
    categories: index,
  }, null, 1) + '\n');
  put('CONTACT-SHEET.png', contactSheet(built));
  return files;
}

// our art only (no disc pixels): per category the CAT strip, the Find Wizard strip and the icons; then the watermarks
function contactSheet(built) {
  const colW = 700, rowH = 108, cols = 2, rows = Math.ceil(built.length / cols);
  const wmS = 1, wmCols = 7, wmW = strips.WM.w * wmS + 8, wmRows = Math.ceil(built.length / wmCols);
  const W = Math.max(cols * colW + 20, wmCols * wmW + 20), H = 40 + rows * rowH + 30 + wmRows * (strips.WM.h * wmS + 26) + 10;
  const sh = new Sheet(W, H, '#31353E');
  sh.text('Deep32 Library category art (Deep32 Workstation): CAT strips, Find Wizard strips, icons 16/32, watermarks. Generated by tools/build.js; final taxonomy (2026-11-06).', 10, 8, '#D9D6C5');
  built.forEach((b, i) => {
    const x = 10 + (i % cols) * colW, y = 32 + Math.floor(i / cols) * rowH;
    sh.text(`${b.cat.order}. ${b.cat.bar_label}  face ${b.cat.face}  ink ${b.cat.ink}`, x, y, '#D9D6C5');
    sh.paste(b.cat_strip, x, y + 16, 1);
    sh.paste(b.fw_strip, x, y + 60, 1);
    sh.paste(b.icon32, x + 350, y + 16, 1);
    sh.paste(b.icon16, x + 390, y + 16, 1);
    sh.paste(b.icon32, x + 412, y + 16, 1);
  });
  const y0 = 40 + rows * rowH + 10;
  built.forEach((b, i) => {
    const x = 10 + (i % wmCols) * wmW, y = y0 + Math.floor(i / wmCols) * (strips.WM.h * wmS + 26);
    sh.text(`${b.cat.order}. ${b.cat.watermark}`.slice(0, 46), x, y, '#D9D6C5');
    sh.paste(b.watermark, x, y + 16, wmS);
  });
  return sh.png();
}

const files = build();
const manifest = {
  schema: 'deep32-d32library-category-art-manifest/1',
  files: [...files].map(([rel, buf]) => ({ path: rel, bytes: buf.length, sha256: sha(buf) })).sort((a, b) => a.path.localeCompare(b.path)),
};
if (check) {
  const old = JSON.parse(fs.readFileSync(path.join(OUT, 'MANIFEST.json'), 'utf8'));
  const a = new Map(old.files.map(f => [f.path, f.sha256])), b = new Map(manifest.files.map(f => [f.path, f.sha256]));
  const diff = [...new Set([...a.keys(), ...b.keys()])].filter(k => a.get(k) !== b.get(k));
  for (const k of diff) { const f = path.join(OUT, k); if (!fs.existsSync(f) || sha(fs.readFileSync(f)) !== b.get(k)) diff.push(`${k} (on disk)`); }
  if (diff.length) { console.log(`DIFFERENT: ${diff.length}\n${diff.slice(0, 20).join('\n')}`); process.exit(1); }
  // and the files on disk must be the ones the manifest names
  for (const f of manifest.files) if (sha(fs.readFileSync(path.join(OUT, f.path))) !== f.sha256) { console.log(`DIFFERENT on disk: ${f.path}`); process.exit(1); }
  console.log(`identical: ${manifest.files.length} files`);
} else {
  fs.rmSync(OUT, { recursive: true, force: true });
  for (const [rel, buf] of files) { const f = path.join(OUT, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, buf); }
  fs.writeFileSync(path.join(OUT, 'MANIFEST.json'), JSON.stringify(manifest, null, 1) + '\n');
  console.log(`wrote ${files.size} files + MANIFEST.json to ${OUT}`);
}
