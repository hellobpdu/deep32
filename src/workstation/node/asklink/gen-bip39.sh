#!/bin/sh
# Emits src/bip39.c from vendor/bip39-english.txt after checking the pin in sas.md.
set -eu
f=$1
want=2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda # SHA-256
got=$(sha256 -q "$f")
[ "$got" = "$want" ] || { echo "gen-bip39: wordlist pin mismatch" >&2; exit 1; }
[ "$(wc -l < "$f" | tr -d ' ')" = 2048 ] || { echo "gen-bip39: not 2048 lines" >&2; exit 1; }
if grep -qv '^[a-z][a-z]*$' "$f"; then echo "gen-bip39: unexpected byte" >&2; exit 1; fi
echo "/* Generated by gen-bip39.sh from vendor/bip39-english.txt, sha256 $want. Do not edit. */"
echo '#include "d32u.h"'
echo
echo 'const char *const bip39_words[2048] = {'
awk '{ printf "\t\"%s\",\n", $1 }' "$f"
echo '};'
