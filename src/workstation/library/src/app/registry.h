/* registry.h: Deep32 Library's registries (W0-F0, build 3). Everything a room, a kind, a helper query or a render
 * operation adds is registered here by name, so that a new room plugs in with new files only (docs/F0-HANDOFF.md).
 *
 * Six tables, all X-free (the screen parser, the tests and the helpers link this file without Xlib):
 *   kinds      control kinds ("button", "wheel", ...): a kind_ops table (library_app.h) per kind
 *   actions    what a control, a menu item or a key does ("goto", "close", "room.atlas", ...): a handler
 *   sources    where a control's text, checked state or decoration comes from ("notice-text", "pin-header", ...)
 *   settings   the settings store's keys (the period design's LIBRARY.INI names: ShowTitleScreen, TextStyle, ...)
 *   queries    e26-lib named queries (src/lib/q_<room>.c; LIB-PROTOCOL.md)
 *   renderops  e26-render named operations (src/render/op_<x>.c; LIB-PROTOCOL.md)
 *
 * Built-in kinds and actions keep the numbers of build 2's enums (scr.h K_* and A_*), so code that tests
 * c->kind == K_WHEEL or c->action == A_GOTO keeps working; a module's kind or action gets the next free number.
 *
 * Named actions and the notice fallback: an action name with a dot ("room.atlas", "find.words") is a named action.
 * A screen file may name one before any module implements it: the parser declares it (no handler), and running a
 * declared action shows today's "coming in a later build" box with its argument as the title ("Atlas" gives
 * "Atlas is coming in a later build of Deep32 Library."). The module that builds the room registers the handler under
 * the same name and no screen file changes. Names without a dot must be registered (built-in) or the parser
 * refuses them, so a misspelt built-in is still caught.
 *
 * Modules: every src/app/kind_*.c, room_*.c and mod_*.c defines void e26_mod_<file name>(void), which registers its
 * kinds, actions, sources and settings; the Makefile collects them into modules.gen.c (e26_modules_register). */
#ifndef E26_REGISTRY_H
#define E26_REGISTRY_H
#include <stddef.h>

enum reg_table { REG_KIND, REG_ACTION, REG_SOURCE, REG_SETTING, REG_QUERY, REG_RENDEROP, REG_NTABLES };

#define REG_NAME 48

typedef struct {
	char name[REG_NAME];
	int id;               /* index in its table (kinds and actions: the K_* / A_* number) */
	const void *impl;     /* the table's own type: kind_ops, action handler, source_ops, setting, query, renderop */
	const char *owner;    /* the module that registered it ("kind_wheel", "room_pinpoint"), "" when only declared */
	int declared;         /* 1: named by a screen or keys file before any module implemented it */
	unsigned flags;       /* per table (REG_A_* for actions) */
} reg_entry;

/* action flags */
#define REG_A_ARG     0x01  /* needs one argument (goto, menu, notice): the parser refuses it without */
#define REG_A_NAMED   0x02  /* a named action (a dot in the name): no handler means the notice fallback */

/* Registers name in table t with an implementation; returns its id. Registering a name that was only declared
 * fills it in (same id); registering an implemented name again replaces the implementation and says so on stderr
 * (two modules claiming one name is a defect the registry lint reports). -1 when the table is full or the name
 * too long. */
int reg_add(int t, const char *name, const void *impl, const char *owner, unsigned flags);
/* The id of name in table t, or -1. */
int reg_find(int t, const char *name);
/* Declares a named action (a dot in the name) without a handler; returns its id (or the registered one). */
int reg_declare(int t, const char *name);
const reg_entry *reg_get(int t, int id);   /* NULL when out of range */
int reg_count(int t);
const char *reg_name(int t, int id);       /* "?" when out of range */
const void *reg_impl(int t, int id);       /* NULL when unknown or only declared */
/* Names that two modules registered (the last one wins at run time); the lint lists them. */
int reg_conflicts(char *out, size_t n);
const char *reg_table_name(int t);

/* the build-2 kinds and actions are in the tables from the start, at their enum numbers (registry.c) */
void reg_builtins(void);

/* modules.gen.c (generated by the Makefile from src/app/{kind,room,mod}_*.c) */
void e26_modules_register(void);
extern const char *const e26_modules_names[];
extern const int e26_modules_count;

#endif
