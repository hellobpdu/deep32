// Desktop Look (d32-look, THEME B8): the per-user look chooser and the data it applies. Update answers 2 and 5
// (the owner 2026-11-06): "can we have the ability to pick themes between the hp-ux and then vue? If so, go", HP-UX CDE
// the default, HP VUE selectable. The public build offers its two reconstructions (cde10, cde21) the same way.
//
// For each look the build offers, the generator writes into <theme>/looks/<id>/:
//   look.res   the look's resources, xrdb syntax with the package's WIDTH steps: palette name, front-panel colour set,
//              workspace backdrops, the CDE enable switches, every font resource. d32-look removes every key named in
//              looks/managed.keys from the session's resource database and loads these in their place, so going back
//              from a look that sets more keys (VUE's faces) leaves nothing of it behind.
//   pixelset   the colour server's "SDT Pixel Set" string for the look's palette at HIGH_COLOR and MEDIUM_COLOR, with
//              the *background and *foreground the colour server writes for Xt clients. On a 24-bit TrueColor screen a
//              pixel is its RGB value, so the string dtsession would publish for the palette is known in advance
//              (checked against a live dtsession on the build VM: Default at HIGH_COLOR, byte for byte).
//   greeter    the dtlogin greeter resources of the look (cde.greeter), for d32-look-greeter.
// How a look is applied, and why (CDE 2.5.4 on Motif 2.3.8; sources: dtstyle ColorMain.c, dtsession SrvPalette.c,
// Motif ColorObj.c):
//   * Resources: the session's RESOURCE_MANAGER, which dtsession saves into the session's dt.resources at logout, and the
//     saved dt.resources of the current and home sessions plus a marked block in ~/.Xdefaults, so the look holds at the
//     next login whichever session is resumed. New windows open in the look at once.
//   * Colour: dtsession's colour server allocates the palette once, at login. On a TrueColor screen Style Manager can
//     only say "The selected palette will take effect at your next session" (dtstyle NEXT_SESSION). Every Motif client
//     (dtwm included) reads its colours from the "SDT Pixel Set" property on the colour server's window before it ever
//     asks the server (ColorObj.c ColorCachePropertyExists), so d32-look rewrites that property with the new palette's
//     pixel set: dtwm, the front panel, the backdrops and every window opened afterwards take the new palette at once,
//     and dtsession starts with it at the next login. On any other visual it falls back to Style Manager's rule.
//   * Window manager: dtwm is restarted the way the Workspace Menu's "Restart Workspace Manager..." does (f.restart),
//     without its confirmation, through dtwm's own request property (_DT_WM_REQUEST, as DtSvc's _DtWmRestartNoConfirm).
//     It rereads the resources: backdrops, front-panel colour set and faces, frame look.
//   * Windows that are already open keep their colours and faces until they are reopened (as with Style Manager).
//   * The login screen is system-wide: d32-look offers it only where doas lets this user run d32-look-greeter, which
//     installs the chosen look's greeter file and nothing else.
const fs = require('fs');
const path = require('path');
const { sets } = require('./common');
const cde = require('./cde');

const PKG_ENABLE = { enableThinThickness: 'True', enableEtchedInMenu: 'True', enableToggleVisual: 'True', enableToggleColor: 'True',
  enableMenuInCascade: 'True', enableDefaultButton: 'True', enableButtonTab: 'True', enableBtn1Transfer: 'button2_transfer',
  enableMultiKeyBindings: 'True', enableDragIcon: 'True', enableCDEColorFactors: 'True' };   // CDE 2.5.4 sys.resources
// the package sys.resources font block (CDE 2.5.4, identical in HP-UX 10.20 and 11.00), keys in its order; sizes per step
const PKG_FONT_KEYS = [['*FontList', 'system', ':'], ['*buttonFontList', 'system', ':'], ['*labelFontList', 'system', ':'],
  ['*textFontList', 'user', ':'], ['*XmText*FontList', 'user', ':'], ['*XmTextField*FontList', 'user', ':'],
  ['*systemFont', 'system', ':'], ['*userFont', 'user', ':'], ['*DtEditor*textFontList', 'user', ':'], ['*Font', 'user', ''],
  ['*FontSet', 'user', '']];

function looksFor(d, priv) { return priv ? d.looks.private : d.looks.public; }
function lookPalette(d, id) { return d.profiles[id].palette || d.palettes.default; }

// the look's resource file: the same key set for every look a build offers (managedKeys checks that)
function lookRes(d, id, label, isDefault, pal = lookPalette(d, id)) {
  const p = d.profiles[id];
  const L = ['!' + '#'.repeat(78), `! Deep32/UX Desktop Look ${id}: ${label}${isDefault ? ', the default' : ''}. ` +
    'Generated by tools/gen.js (tools/gen/look.js).',
  '! d32-look removes every key of managed.keys from the session resources and loads this file with xrdb (cpp: the',
  '! WIDTH steps). No hash lines but the WIDTH steps, no quotes, no slash-star or double slash.', '!' + '#'.repeat(78)];
  const put = (k, v) => L.push(`${k}: `.padEnd(34) + v);
  L.push('! Colour: the palette dtsession loads at login, and the front panel colour set');
  put('*0*ColorPalette', pal + '.dp');
  put('Dtwm*primaryColorSetId', String(p.panelColorSet));
  put('Dtwm*secondaryColorSetId', String(p.panelColorSet));
  L.push('! Backdrops, and the workspace colour sets where the look sets them (otherwise dtwm assigns its own)');
  const pp = Object.assign({}, p, { backdropDefault: p.backdropDefault || d.workspaces[0].backdrop[id] });
  L.push(...cde.backdropLines(Object.assign({}, d, { profiles: Object.assign({}, d.profiles, { [id]: pp }) }), id));
  if (p.wsColorSets) d.workspaces.forEach((w, i) => put(`Dtwm*${w.id}*colorSetId`, String(p.wsColorSets[i])));
  L.push('! Look switches (CDE-SPEC 2.0): every switch written, the package value where the look leaves it');
  for (const k of Object.keys(PKG_ENABLE)) put('*' + k, (p.enable && p.enable[k]) || PKG_ENABLE[k]);
  L.push('! Faces');
  if (p.fonts) {
    const F = p.fonts;
    const fl = v => v + ':';
    for (const [k, v] of [['*FontList', fl(F.system)], ['*buttonFontList', fl(F.system)], ['*labelFontList', fl(F.system)],
      ['*textFontList', fl(F.user)], ['*XmText*FontList', fl(F.user)], ['*XmTextField*FontList', fl(F.user)],
      ['*systemFont', fl(F.system)], ['*userFont', fl(F.user)], ['*DtEditor*textFontList', fl(F.user)], ['*Font', F.user],
      ['*FontSet', F.user], ['Dtwm*FrontPanel*highResFontList', fl(F.panelHigh)], ['Dtwm*FrontPanel*mediumResFontList', fl(F.panelMedium)],
      ['Dtwm*FrontPanel*lowResFontList', fl(F.panelLow)], ['Dtwm*icon*fontList', fl(F.icon || F.system)]]) put(k, v);
  } else {
    // the package block, *Font with its registry pinned as the theme overlay does (cde.sysResources)
    const block = z => PKG_FONT_KEYS.map(([k, fam, colon]) => k === '*Font'
      ? `${k}: `.padEnd(34) + `-dt-interface user-medium-r-normal-${z}*-*-*-*-*-*-*-iso8859-1`
      : `${k}: `.padEnd(34) + `-dt-interface ${fam}-medium-r-normal-${z}*-*-*-*-*-*-*-*-*${colon}`);
    L.push('# if WIDTH > 1175', ...block('m'), '# else', '# if WIDTH < 851', ...block('xs'), '# else', ...block('s'), '# endif', '# endif');
  }
  return L.join('\n') + '\n';
}

const resKeys = txt => [...new Set(txt.split('\n').filter(l => l && !/^[!#]/.test(l)).map(l => l.slice(0, l.indexOf(':')).trim()))];
// every key any offered look sets, plus the colour server's Xt colours: what d32-look clears before loading a look
function managedKeys(texts) {
  const all = new Set(['*background', '*foreground']);
  for (const t of texts) for (const k of resKeys(t)) all.add(k);
  return [...all].sort();
}

// "SDT Pixel Set" (SrvPalette.c convert_pixel_set + _DtCacheProperties): "<use>_" then bg_fg_ts_bs_sc_ in lower-case hex
// for sets 1..8, then the version character '1'. The Xt colours: set 5 at HIGH_COLOR, set 2 otherwise (InitializeDtcolor).
const USE_CODE = { HIGH_COLOR: 3, MEDIUM_COLOR: 2 };
function pixelSet(pal, use) {
  const s = sets(pal, use).slice(1);
  const hex = h => parseInt(h.slice(1), 16).toString(16);
  return `${USE_CODE[use]}_` + s.map(c => [c.bg, c.fg, c.ts, c.bs, c.sc].map(hex).join('_') + '_').join('') + '1';
}
function pixelSetFile(id, pal) {
  const L = [`# Deep32/UX Desktop Look ${id}: palette ${pal.name}. COLOUR-USE PIXEL-SET XT-BACKGROUND XT-FOREGROUND`,
    '# The colour server string on a 24-bit TrueColor screen (pixel = RGB); generated by tools/gen/look.js.'];
  for (const use of ['HIGH_COLOR', 'MEDIUM_COLOR']) {
    const s = sets(pal, use); const xt = s[use === 'HIGH_COLOR' ? 5 : 2];
    L.push(`${use} ${pixelSet(pal, use)} ${xt.bg16.toUpperCase()} ${xt.fg16.toUpperCase()}`);
  }
  return L.join('\n') + '\n';
}

// looks.conf: id|label|default|palette|panel colour set|backdrops|faces|login|description
function looksConf(d, priv, defId, palOf = id => lookPalette(d, id)) {
  const L = ['# Deep32/UX Desktop Look: the looks this build offers (d32-look reads this file). Generated by tools/gen/look.js.',
    '# id|label|default|palette|panel colour set|backdrop|faces|login screen|description'];
  for (const { id, label } of looksFor(d, priv)) {
    const p = d.profiles[id];
    const faces = p.fonts ? 'HP Swiss 742 and Prestige (VUE 3.0)' : 'Deep32 System and Deep32 User (the CDE interface faces)';
    const bds = p.deepBackdrop ? 'the VUE workspace frames, as vuewm drew them' : [...new Set(d.workspaces.map(w => w.backdrop[id]))].join(', ');
    const login = p.greeter ? (p.greeter.logo.includes('vue') ? 'HP VUE login (HEWLETT PACKARD wordmark)' : 'HP CDE login (HP logo)') : 'Deep32 login (emblem)';
    L.push([id, label + (id === defId ? ' (default)' : ''), id === defId ? 'yes' : 'no', palOf(id), p.panelColorSet, bds, faces, login,
      (p.lookBlurb || p.shownAs).replace(/\|/g, '/')].join('|'));
  }
  return L.join('\n') + '\n';
}

