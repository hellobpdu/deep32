'use strict';
// The System V face of the text console (SYSV-FLAVOUR 2.6-2.7, 3.3, 5; LOOK-SOUND 3.3-3.5; DISTRO-DESIGN 6.7):
//   - lib/d32-banner.sh: POSIX sh functions d32ready and rc.shutdown call (header, checklist line, ready line,
//     asterisk box, motd, shutdownlog line);
//   - goldens built here by an independent implementation of the same rules, from fixture values, so validate.js
//     can run the shell library and diff byte for byte (T-C1 checklist, T-C2 motd, T-C3 getty, T-C5 shutdown);
//   - /etc/issue, the gettytab default entry and its idempotent applier, the login class that shows the motd.
// Geometry: 5-space indent, dot leader to column 74, one space, status from column 76; a status too long to end
// by column 80 (FAIL *, STARTING) is right-aligned to column 80 instead, so no line is ever wider than 80.

const W = 80;
const centre = s => ' '.repeat(Math.floor((W - [...s].length) / 2)) + s;

function item(msg, status) {
  const col = 75 + status.length > W ? W + 1 - status.length : 76;
  const pre = `     ${msg} `;
  const n = col - 2 - pre.length;
  if (n < 3) throw new Error(`checklist message too long: "${msg}"`);
  return pre + '.'.repeat(n) + ' ' + status;
}
function header(title) { return [`     ${title}`, `     ${'_'.repeat(title.length)}`, '']; }
function box(lines) {
  const star = '*'.repeat(77);
  return [star, '*', ...lines.map(l => l ? `* ${l}` : '*'), '*', star];
}

// Fixture values: the real ones SYSV-FLAVOUR recorded from rag_status on 2026-11-05, and a plausible First light
// checklist from DISTRO-DESIGN 6.7's local probes. Used only for goldens.
const FIX = {
  date: 'Thu Nov  5 09:12', gen: 'p9er-20261102', corpus: 'corpus-v9', docs: '1493', fp: 'e350da93',
  pins: 'IOS XE 17.9, SD-WAN 20.9, Catalyst Center 2.3, ISE 3.1', gate: 'G2 subset 0 diffs', backup: '20261102-1548 complete',
  checklist: [
    ['Verify the active slot (signify)', 'OK'],
    ['Check the boot loader hash (ESP)', 'OK'],
    ['Load the packet filter (no inbound rules)', 'OK'],
    ['Raise the security level (securelevel 2)', 'OK'],
    ['Check the audit chain', 'OK'],
    ['Start the library service (deep32d)', 'OK'],
    ['Start local search (LCL)', 'STARTING'],
    ['Network checks (see the front-panel lamps)', 'N/A'],
  ],
  failing: [['Check the audit chain', 'FAIL *'], ['Start the library service (deep32d)', 'WARN']],
  shutdown: [['Stop local search (LCL)', 'OK'], ['Stop the library service (deep32d)', 'OK'], ['Close the audit chain', 'OK']],
  halt: { time: '22:41', day: 'Thu', mon: 'Nov', dom: '5', year: '2026', kind: 'Halt', who: 'deep32!the desktop user' },
};

function goldens(d) {
  const I = d.identity, S = d.sysv;
  const g = {};
  const chk = [...header(S.checklistTitle), ...FIX.checklist.map(([m, s]) => item(m, s)), '', S.readyLine, '', ...box(S.dtloginBox)];
  g['T-C1.checklist.txt'] = chk.join('\n') + '\n';
  const chkFail = [...header(S.checklistTitle), ...FIX.failing.map(([m, s]) => item(m, s)), '', ...S.failFootnotes, '', S.readyLine];
  g['T-C1b.checklist-fail.txt'] = chkFail.join('\n') + '\n';
  g['T-C2.motd.txt'] = motd(d, FIX);
  g['T-C3.getty.txt'] = `\r\n\r\n${I.node} [${I.os} Release ${d.release}] (see /etc/issue)\r\n\r\nConsole Login: `;
  const sd = [...header(S.shutdownTitle), ...FIX.shutdown.map(([m, s]) => item(m, s))];
  g['T-C5.shutdown.txt'] = sd.join('\n') + '\n';
  const h = FIX.halt;
  g['T-C6.shutdownlog.txt'] = `${h.time}  ${h.day} ${h.mon} ${h.dom.padStart(2)}, ${h.year}.  ${h.kind}:  (by ${h.who})\n`;
  return g;
}

function motd(d, v) {
  const I = d.identity;
  const left = `${I.os} Release ${d.release}`, right = `${I.node}  ${v.date}`;
  return [
    left + ' '.repeat(W - left.length - right.length) + right,
    '',
    `  Library generation ${v.gen} (${v.corpus}): ${v.docs} documents, fp ${v.fp}`,
    `  Pinned releases: ${v.pins}`,
    `  Last gate: ${v.gate}    Last backup: ${v.backup}`,
    '',
    '  "man deep32" for the manual, "sam" or "smitty" to administer, "search" finds.',
    '',
    ...I.noticeLines.map(centre),
    '',
  ].join('\n');
}

// The shell library. Notice lines are pre-centred by the generator (shell ${#var} counts bytes in the C locale).
function bannerLib(d) {
  const I = d.identity, S = d.sysv;
  const q = s => "'" + s.replace(/'/g, "'\\''") + "'";
  return `# d32-banner.sh: the Deep32/UX console banners (d32-theme ${d.release}). POSIX sh; sourced by d32ready (ksh)
# and /etc/rc.shutdown. Generated by tools/gen.js; the same rules build the text goldens (validate.js T-C*).
# Geometry (SYSV-FLAVOUR 2.6): 5-space indent, dot leader to column 74, status from column 76; a status that
# would pass column 80 is right-aligned to column 80. Messages are ASCII except the handling notice
# (D32_NOTICE1/2): SYSV-FLAVOUR 2.5 locks it with U+00B7 MIDDLE DOT, written here as UTF-8 (C2 B7). A console or
# terminal that is not UTF-8 shows those two bytes as two characters; ISO 9.2.2's P1 locale matrix decides.

D32_OS=${q(I.os)}
D32_NODE=${q(I.node)}
D32_RELEASE=${q(d.release)}
D32_NOTICE1=${q(centre(I.noticeLines[0]))}
D32_NOTICE2=${q(centre(I.noticeLines[1]))}

d32_header() {	# d32_header TITLE
	_t=$1; _u=''; _i=0
	while [ $_i -lt \${#_t} ]; do _u="\${_u}_"; _i=$((_i + 1)); done
	printf '     %s\\n     %s\\n\\n' "$_t" "$_u"
}

d32_item() {	# d32_item MESSAGE STATUS
	_m=$1; _s=$2
	if [ $((75 + \${#_s})) -gt 80 ]; then _c=$((81 - \${#_s})); else _c=76; fi
	_pre="     $_m "
	_n=$((_c - 2 - \${#_pre})); _d=''
	while [ $_n -gt 0 ]; do _d="\${_d}."; _n=$((_n - 1)); done
	printf '%s%s %s\\n' "$_pre" "$_d" "$_s"
}

d32_footnotes() {
	printf '%s\\n%s\\n' ${q(S.failFootnotes[0])} ${q(S.failFootnotes[1])}
}

d32_ready() { printf '\\n%s\\n' ${q(S.readyLine)}; }

d32_box() {	# d32_box LINE... (an empty argument prints a bare "*")
	_s='*****************************************************************************'
	printf '%s\\n*\\n' "$_s"
	for _l in "$@"; do if [ -n "$_l" ]; then printf '* %s\\n' "$_l"; else printf '*\\n'; fi; done
	printf '*\\n%s\\n' "$_s"
}

d32_dtlogin_box() { d32_box ${S.dtloginBox.map(q).join(' ')}; }

d32_motd() {	# d32_motd DATE GEN CORPUS DOCS FP PINS GATE BACKUP
	_l="$D32_OS Release $D32_RELEASE"; _r="$D32_NODE  $1"
	_n=$((80 - \${#_l} - \${#_r})); _p=''
	while [ $_n -gt 0 ]; do _p="$_p "; _n=$((_n - 1)); done
	printf '%s%s%s\\n\\n' "$_l" "$_p" "$_r"
	printf '  Library generation %s (%s): %s documents, fp %s\\n' "$2" "$3" "$4" "$5"
	printf '  Pinned releases: %s\\n' "$6"
	printf '  Last gate: %s    Last backup: %s\\n\\n' "$7" "$8"
	printf '  "man deep32" for the manual, "sam" or "smitty" to administer, "search" finds.\\n\\n'
	printf '%s\\n%s\\n' "$D32_NOTICE1" "$D32_NOTICE2"
}

d32_shutdownlog() {	# d32_shutdownlog KIND WHO  -> one /var/adm/shutdownlog line (SYSV-FLAVOUR 3.3)
	printf '%s  %s.  %s:  (by %s)\\n' "$(date '+%H:%M')" "$(date '+%a %b %e, %Y')" "$1" "$2"
}
`;
}

// Fixture driver run by validate.js under sh: prints the same texts as goldens() from the same values.
function bannerFixture() {
  const f = FIX;
  const items = (list) => list.map(([m, s]) => `d32_item '${m.replace(/'/g, "'\\''")}' '${s}'`).join('\n');
  return {
    'T-C1.checklist.txt': `d32_header 'Deep32 Start-up in progress'\n${items(f.checklist)}\nd32_ready\nprintf '\\n'\nd32_dtlogin_box\n`,
    'T-C1b.checklist-fail.txt': `d32_header 'Deep32 Start-up in progress'\n${items(f.failing)}\nprintf '\\n'\nd32_footnotes\nd32_ready\n`,
    'T-C2.motd.txt': `d32_motd '${f.date}' '${f.gen}' '${f.corpus}' '${f.docs}' '${f.fp}' '${f.pins}' '${f.gate}' '${f.backup}'\n`,
    'T-C5.shutdown.txt': `d32_header 'System shutdown in progress'\n${items(f.shutdown)}\n`,
  };
}

function issue(d) {
  const I = d.identity;
  return [`${I.node} [${I.os} Release ${d.release}] (see /etc/issue)`, '', ...I.noticeLines.map(centre), ''].join('\n');
}
// gettytab(5): im = banner, lm = login prompt; a colon inside a capability is written \\072 (LOOK-SOUND 3.3).
function gettytab(d) {
  const I = d.identity;
  return `default:\\\n\t:np:im=\\r\\n\\r\\n${I.node} [${I.os} Release ${d.release}] (see /etc/issue)\\r\\n\\r\\n:lm=Console Login\\072 :sp#9600:\n`;
}
// POSIX sh + awk: replace the "default" entry of /etc/gettytab with ours, once; prints the new file on stdout.
const GETTY_APPLY = `#!/bin/sh
# apply-gettytab.sh ENTRY GETTYTAB: print GETTYTAB with its "default" entry replaced by ENTRY (d32-theme).
# Idempotent; leaves every other entry untouched. install.site runs it and installs the result.
set -eu
entry=$1; tab=$2
awk -v entryfile="$entry" '
BEGIN { while ((getline l < entryfile) > 0) e = e l "\\n"; close(entryfile) }
skipping && /\\\\$/ { next }
skipping { skipping = 0; next }
/^default[:|]/ { printf "%s", e; if ($0 ~ /\\\\$/) skipping = 1; done = 1; next }
{ print }
END { if (!done) printf "%s", e }
' "$tab"
`;
function loginClass(d) {
  return [
    '# /etc/login.conf.d/d32: the login class of the Deep32 user (d32-theme). the desktop user sees the Deep32/UX motd;',
    '# root keeps the stock /etc/motd that /etc/rc rewrites (LOOK-SOUND 3.4). Limits come from "default".',
    'd32:\\',
    '\t:welcome=/etc/d32/motd:\\',
    '\t:tc=default:',
    '',
  ].join('\n');
}

module.exports = { goldens, bannerLib, bannerFixture, issue, gettytab, GETTY_APPLY, loginClass, motd, item, FIX };
