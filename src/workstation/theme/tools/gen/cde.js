'use strict';
// CDE configuration files: palettes, the sys.resources overlay and the two look profiles, sys.dtwmrc, the dtlogin
// greeter resources, the Xsession.d scripts and dthello's text.
const { due, sets } = require('./common');

const HDR = (d, what) => `Deep32/UX ${d.release} ${what} (d32-theme). Generated by tools/gen.js; edit src/theme-data.js, not this file.`;

// ---- palettes ------------------------------------------------------------------------------------------------
// CDE's .dp format (SrvFile_io.c ParsePaletteInfo): one XParseColor background per line, CS1..CS8, nothing else.
function dp(pal) { return pal.lines.join('\n') + '\n'; }

// ---- sys.resources overlay -------------------------------------------------------------------------------------
// Merged by dtsession_res after the package's sys.resources (dtloadresources: rFactory then rCustom), through xrdb,
// so cpp sees it: no '#' lines except the WIDTH size steps, no apostrophes or quotes in comments, no slash-star or double slash.
function profileRes(d, prof) {
  const p = d.profiles[prof];
  const lines = [`! Look profile ${prof}: ${p.shownAs}. The CDE enable resources (CDE-SPEC 2.0).`];
  for (const [k, v] of Object.entries(p.enable)) lines.push(`*${k}:`.padEnd(32) + v);
  return lines;
}
function sysResources(d, prof, pal) {
  const p = d.profiles[prof];
  const L = [];
  L.push('!' + '#'.repeat(78));
  L.push('! ' + HDR(d, 'desktop resources'));
  L.push(`! Profile ${prof} (${p.shownAs}), palette ${pal}, ${d.palettes.colourUse}.`);
  L.push('! Merged by dtsession after the package sys.resources. Style Manager choices saved in the session win.');
  L.push('!' + '#'.repeat(78));
  L.push('', '! Colour (DISTRO-DESIGN 6.1)');
  const rows = [
    ['*0*ColorPalette', pal + '.dp'], ['*ColorUse', d.palettes.colourUse], ['*shadowPixmaps', 'False'],
    ['*dynamicColor', 'True'], ['*foregroundColor', 'Dynamic'],
    ['Dtwm*primaryColorSetId', String(p.panelColorSet)], ['Dtwm*secondaryColorSetId', String(p.panelColorSet)],
  ];
  // at least one space after the colon, also for keys of 31 characters or more (T-RES reads resource lines that way)
  const put = (rs) => rs.forEach(([k, v]) => L.push(`${k}: `.padEnd(32) + v));
  put(rows);
  L.push('', '! Window manager (DISTRO-DESIGN 6.6, CDE-SPEC 4)');
  put(d.dtwm.resources);
  L.push('', '! Workspaces: names and backdrops (DISTRO-DESIGN 6.6)');
  put(d.workspaces.map(w => [`Dtwm*${w.id}*title`, w.title]));
  L.push(...backdropLines(d, prof));
  if (p.wsColorSets) L.push(...wsColourLines(d, prof));
  L.push('');
  L.push(...profileRes(d, prof));
  L.push('*DtTerm*shadowThickness:'.padEnd(32) + '1');
  L.push('', '! Session, terminal and toolkit dpi (DISTRO-DESIGN 6.6-6.7, ISO-DESIGN 9.1)');
  put(d.session);
  // VM proof 2026-11-05: a plain *Font (one font, not a set) with a wildcard registry is opened by the X server as the
  // first matching name, and in the alias table the iso10646-1 fallback member sorts before iso8859-1, so Xt programs
  // got misc-fixed instead of Deep32 User. Pin the registry for *Font, with the package sys.resources size steps.
  if (p.fonts) {
    // a profile with its own faces (vue: VUE's sys.font at the 1280x1024 step) names them for every font resource the
    // package sys.resources sets, so nothing falls back to the interface aliases
    const F = p.fonts;
    L.push('', `! Fonts of the ${prof} profile (private build): system ${F.system}, user ${F.user}`);
    const fl = v => v + ':';
    put([['*FontList', fl(F.system)], ['*buttonFontList', fl(F.system)], ['*labelFontList', fl(F.system)], ['*textFontList', fl(F.user)],
      ['*XmText*FontList', fl(F.user)], ['*XmTextField*FontList', fl(F.user)], ['*systemFont', fl(F.system)], ['*userFont', fl(F.user)],
      ['*DtEditor*textFontList', fl(F.user)], ['*Font', F.user], ['*FontSet', F.user],
      ['Dtwm*FrontPanel*highResFontList', fl(F.panelHigh)], ['Dtwm*FrontPanel*mediumResFontList', fl(F.panelMedium)],
      ['Dtwm*FrontPanel*lowResFontList', fl(F.panelLow)], ['Dtwm*icon*fontList', fl(F.icon || F.system)]]);
    return L.join('\n') + '\n';
  }
  L.push('', '! Xt single-font resource pinned to the Deep32 User face (iso8859-1), same size steps as sys.resources');
  const fontAt = z => '*Font:'.padEnd(32) + `-dt-interface user-medium-r-normal-${z}*-*-*-*-*-*-*-iso8859-1`;
  L.push('# if WIDTH > 1175', fontAt('m'), '# else', '# if WIDTH < 851', fontAt('xs'), '# else', fontAt('s'), '# endif', '# endif');
  return L.join('\n') + '\n';
}

// Workspace backdrops of a profile: one name each, or for a profile with VUE's full-screen backdrop (deepBackdrop) the
// picture drawn at the screen's size, chosen by cpp's WIDTH and HEIGHT as the package steps its fonts
function backdropLines(d, prof) {
  const p = d.profiles[prof];
  const keys = d.workspaces.map(w => [`Dtwm*${w.id}*backdrop*image`, w.backdrop[prof]]);
  if (p.backdropDefault) keys.push(['Dtwm*backdrop*image', p.backdropDefault]);
  // the workspace keys in order, then the default key (named as workspace One's)
  if (p.deepBackdrop) return keys.flatMap(([k], i) => require('./vuedeep').resourceSteps(k, i < d.workspaces.length ? i : 0));
  return keys.map(([k, v]) => `${k}: `.padEnd(32) + v);
}
// dtwm's per-workspace colour set (the workspace's backdrop and its switch button): VUE's One to Four used 8, 7, 6, 5
function wsColourLines(d, prof) {
  return d.workspaces.map((w, i) => `Dtwm*${w.id}*colorSetId: `.padEnd(32) + d.profiles[prof].wsColorSets[i]);
}

// ---- sys.dtwmrc --------------------------------------------------------------------------------------------------
// The stock file is the C-locale text of CDE 2.5.3 sys.dtwmrc.tmsg (messages 6-14), reproduced here with the
// Deep32 additions marked. dtwm reads ~/.dt/dtwmrc, else /etc/dt/config/C/sys.dtwmrc, else the package copy.
function dtwmrc(d, release, opts = {}) {
  const extraRoot = d.dtwm.rootMenuExtra.filter(r => due(r[2], release));
  const keys = d.dtwm.keys.filter(k => due(k[3], release)).concat(opts.vm ? d.dtwm.vmKeys : []);
  const pad = (s, n) => s + ' '.repeat(Math.max(1, n - s.length));
  const out = [];
  out.push('!' + '#'.repeat(78));
  out.push('! ' + HDR(d, 'window manager resource description file'));
  out.push('! Base: CDE 2.5.3 sys.dtwmrc, C locale (LGPL; The Open Group and the CDE contributors).');
  out.push('! Deep32 additions are marked "Deep32". Personal copies go in $HOME/.dt/dtwmrc.');
  out.push('!' + '#'.repeat(78), '');
  out.push('Menu DtRootMenu', '{');
  out.push(`    ${pad('"Workspace Menu"', 34)}f.title`);
  out.push(`    ${pad('"Shuffle Up"', 34)}f.circle_up`);
  out.push(`    ${pad('"Shuffle Down"', 34)}f.circle_down`);
  out.push(`    ${pad('"Refresh"', 34)}f.refresh`);
  out.push(`    ${pad('"Minimize/Restore Front Panel"', 34)}f.toggle_frontpanel`);
  if (extraRoot.length) {
    out.push(`     ${pad('no-label', 33)}f.separator`);
    out.push('!   Deep32');
    for (const [label, fn] of extraRoot) out.push(`    ${pad(label, 34)}${fn}`);
  }
  out.push(`     ${pad('no-label', 33)}f.separator`);
  out.push(`    ${pad('"Restart Workspace Manager..."', 34)}f.restart`);
  out.push(`     ${pad('no-label', 33)}f.separator`);
  out.push(`    ${pad('"Log out..."', 34)}f.action ExitSession`);
  out.push('}', '');
  out.push('Menu DtPanelMenu', '{');
  for (const [l, m, f] of [['Restore', '_R', 'f.normalize'], ['Move', '_M', 'f.move'], ['Minimize', '_n', 'f.minimize'],
    ['Lower', '_L', 'f.lower'], ['Refresh', '_f', 'f.refresh']]) out.push(`    ${pad(l, 18)}${pad(m, 8)}${f}`);
  out.push(`     ${pad('no-label', 25)}f.separator`);
  out.push(`    ${pad('"Log out..."', 18)}${pad('_o', 8)}f.action ExitSession`);
  out.push('}', '');
  const winMenu = (name, accels) => {
    out.push(`Menu ${name}`, '{');
    const items = [['"Restore"', '_R', 'Alt<Key>F5', 'f.normalize'], ['"Move"', '_M', 'Alt<Key>F7', 'f.move'],
      ['"Size"', '_S', 'Alt<Key>F8', 'f.resize'], ['"Minimize"', '_n', 'Alt<Key>F9', 'f.minimize'],
      ['"Maximize"', '_x', 'Alt<Key>F10', 'f.maximize'], ['"Lower"', '_L', 'Alt<Key>F3', 'f.lower'], null,
      ['"Occupy Workspace..."', '_O', '', 'f.workspace_presence'], ['"Occupy All Workspaces"', '_A', '', 'f.occupy_all'],
      ['"Unoccupy Workspace"', '_U', '', 'f.remove'], null, ['"Close"', '_C', 'Alt<Key>F4', 'f.kill']];
    for (const it of items) {
      if (!it) { out.push(`     ${pad('no-label', 45)}f.separator`); continue; }
      const acc = accels === 'all' ? it[2] : accels === 'close' && it[3] === 'f.kill' ? it[2] : '';
      out.push(`    ${pad(it[0], 26)}${pad(it[1], 6)}${pad(acc, 14)}${it[3]}`);
    }
    out.push('}', '');
  };
  winMenu('SampleWindowMenu', 'close');
  winMenu('NoAcceleratorWindowMenu', 'none');
  out.push('Keys DtKeyBindings', '{');
  const stockKeys = [['Shift<Key>Escape', 'icon|window', 'f.post_wmenu'], ['Alt<Key>space', 'icon|window', 'f.post_wmenu'],
    ['Alt<Key>Tab', 'root|icon|window', 'f.next_key'], ['Alt Shift<Key>Tab', 'root|icon|window', 'f.prev_key'],
    ['Alt<Key>Escape', 'root|icon|window', 'f.next_key'], ['Alt Shift<Key>Escape', 'root|icon|window', 'f.prev_key'],
    ['Alt<Key>Down', 'root|icon|window', 'f.circle_down'], ['Alt<Key>Up', 'root|icon|window', 'f.circle_up'],
    ['Alt Ctrl Shift<Key>exclam', 'root|icon|window', 'f.set_behavior'], ['Alt<Key>F6', 'window', 'f.next_key transient'],
    ['Alt<Key>F10', 'root|icon|window', 'f.menu DtRootMenu']];
  // VM proof 2026-11-05: dtwm grabs f.set_behavior's "Alt Ctrl Shift<Key>exclam" as keycode 10 with Ctrl+Alt, so in
  // the VM variant Ctrl+Alt+1 opened "Switch to Default Behavior?" instead of workspace One. The VM variant drops
  // that one stock binding (the key toggles CDE's look off anyway); the hardware file keeps it.
  for (const [k, c, f] of stockKeys.filter(s => !(opts.vm && s[2] === 'f.set_behavior'))) out.push(`    ${pad(k, 30)}${pad(c, 20)}${f}`);
  out.push('!   Deep32: Mod4 (the Windows key) only; Ctrl+Left/Right and Alt+letter stay with the applications');
  for (const [k, c, f] of keys) out.push(`    ${pad(k, 30)}${pad(c, 20)}${f}`);
  out.push('}', '');
  out.push('Buttons DtButtonBindings', '{');
  for (const [b, c, f] of [['<Btn1Down>', 'root', 'f.marquee_selection'], ['<Btn3Down>', 'root', 'f.menu  DtRootMenu'],
    ['<Btn1Down>', 'frame|icon', 'f.raise'], ['<Btn3Down>', 'frame|icon', 'f.post_wmenu'], ['Alt<Btn1Down>', 'icon|window', 'f.move'],
    ['Alt<Btn3Down>', 'window', 'f.minimize']]) out.push(`    ${pad(b, 20)}${pad(c, 20)}${f}`);
  out.push('}', '');
  winMenu('DefaultWindowMenu', 'all');
  out.push('Keys DefaultKeyBindings', '{');
  for (const [k, c, f] of stockKeys.filter(s => !/Down|Up|F10/.test(s[0]))) out.push(`    ${pad(k, 30)}${pad(c, 20)}${f}`);
  out.push('}', '');
  out.push('Buttons DefaultButtonBindings', '{');
  out.push(`    ${pad('<Btn1Down>', 20)}${pad('frame|icon', 20)}f.raise`);
  out.push(`    ${pad('<Btn3Down>', 20)}${pad('icon', 20)}f.post_wmenu`);
  out.push('}', '');
  out.push('! End of the dtwmrc file');
  return out.join('\n') + '\n';
}

// ---- dtlogin greeter ------------------------------------------------------------------------------------------
// dtlogin merges every file of /etc/dt/config/C/Xresources.d into its resources with XrmMergeDatabases, sorted by
// full path with strcoll, the later file overriding (dtlogin session.c LoadAltDtsResources). The package installs
// 9999.session there as an @sample that sets the OpenBSD logo, so this file is named to sort after it.
const GREETER_FILE = 'etc/dt/config/C/Xresources.d/9999.zz-d32';
function greeter(d, prof, palName, palettes) {
  const s = sets(palettes[palName], d.palettes.colourUse);
  const p = d.profiles[prof];
  const L = ['!' + '#'.repeat(78), '! ' + HDR(d, 'login screen resources'),
    `! Profile ${prof}, palette ${palName}. dtlogin has no colour server, so colours are written out.`,
    '! Read with XrmGetFileDatabase (no cpp); later written out and loaded with xrdb (cpp), so: no hash lines,',
    '! no quotes or apostrophes, no slash-star and no double slash anywhere in this file.',
    '!' + '#'.repeat(78)];
  const put = (k, v) => L.push(`${k}:`.padEnd(40) + v);
  const font = (fam, size) => `-dt-interface ${fam}-medium-r-normal-${size}*-*-*-*-*-*-*-*-*`;
  L.push('', '! Greeting and buttons (LOOK-SOUND 2.8.1, SYSV-FLAVOUR 4)');
  put('Dtlogin*greeting.labelString', d.dtlogin.greeting);
  put('Dtlogin*greeting.persLabelString', d.dtlogin.persGreeting);
  put('Dtlogin*clear_button.labelString', d.dtlogin.clearLabel);
  const G = p.greeter || null;      // a profile with its own greeter (hp, vue: the genuine HP login, private build)
  put('Dtlogin*logo*bitmapFile', G ? G.logo : d.dtlogin.logo);
  if (G && G.labelFont) {
    L.push('', `! Fonts of the ${prof} profile`);
    put('Dtlogin*greeting.fontList', G.greetingFont + ':');
    put('Dtlogin*labelFont', G.labelFont);
    put('Dtlogin*textFont', G.textFont);
    put('Dtlogin*MessageBox*labelFontList', G.labelFont + ':');
  } else {
    L.push('', '! Fonts: Deep32 System and Deep32 User through the -dt-interface aliases');
    put('Dtlogin*greeting.fontList', font('system', d.dtlogin.fonts.greeting) + ':');
    put('Dtlogin*labelFont', font('system', d.dtlogin.fonts.label));
    put('Dtlogin*textFont', font('user', d.dtlogin.fonts.text));
    put('Dtlogin*MessageBox*labelFontList', font('system', d.dtlogin.fonts.label) + ':');
  }
  if (G) {
    L.push('', `! Colours of the ${prof} profile: the HP dtlogin as captured on HP-UX 11.00 and documented in its Xresources`);
    put('Dtlogin*background', G.background); put('Dtlogin*foreground', G.foreground);
    // dtgreet's full-screen "table" (vgmain.c: "black background for everything"): black around the dialog, as captured
    if (G.screenBackground) put('Dtlogin*table.background', G.screenBackground);
    put('Dtlogin*greeting.background', G.background); put('Dtlogin*greeting.foreground', G.foreground);
    put('Dtlogin*logo*background', G.logoBackground);
    put('Dtlogin*highlightColor', G.highlightColor);
    put('Dtlogin*XmTextField*background', G.textBackground); put('Dtlogin*XmTextField*foreground', G.textForeground);
  } else {
    L.push('', `! Colours: ${palName} colour sets written out (CS5 matte, CS3 behind the logo, CS1 focus)`);
    put('Dtlogin*background', s[5].bg); put('Dtlogin*foreground', s[5].fg);
    put('Dtlogin*greeting.background', s[5].bg); put('Dtlogin*greeting.foreground', s[5].fg);
    put('Dtlogin*logo*background', s[3].bg);
    put('Dtlogin*highlightColor', s[1].bg);
    put('Dtlogin*XmTextField*background', s[4].bg); put('Dtlogin*XmTextField*foreground', s[4].fg);
  }
  L.push('', `! Look profile ${prof}: overrides the thin settings in the package Xresources`);
  for (const [k, v] of Object.entries(p.enable)) put('*' + k, v);
  put('*highlightThickness', String(p.thickness));
  put('*DtMenuButton*shadowThickness', String(p.thickness));
  for (const w of (G && G.thinWidgets) || []) put(`*${w}*shadowThickness`, '1');
  return L.join('\n') + '\n';
}

// ---- Xsession.d ---------------------------------------------------------------------------------------------------
// Xsession (ksh) sources every executable file of /etc/dt/config/Xsession.d, then /usr/local/dt/config/Xsession.d,
// after it has set dtstart_hello[0] and before StartFirst runs it (Xsession.src).
function hello(d) {
  return [
    '# ' + HDR(d, 'transition screen'),
    '# Sourced by Xsession (ksh). Replaces the package hello screen, whose text is a vendor copyright block with a',
    '# rights legend (DISTRO-DESIGN 6.7). GetFirst checks that the first word is executable.',
    `dtstart_hello[0]="$DT_BINPATH/dthello -bground cornflowerblue -fground white -string 'Starting the ${d.identity.os} Desktop . . .' -file /etc/dt/config/C/d32.copyright &"`,
    '',
  ].join('\n');
}
function env(d) {
  const P = d.paths;
  return [
    '# ' + HDR(d, 'toolkit environment'),
    '# Sourced by Xsession (ksh) for every CDE session. Environment only: nothing is started here.',
    '',
    '# Files open in the right program (CDE dtopen helpers, DISTRO-DESIGN 3.7): first match on PATH wins.',
    `export DTOPEN_VIMAGE="/usr/local/bin/xv"`,
    `export DTOPEN_VVIDEO="${P.D32LBIN}/d32play /usr/local/bin/mpv"`,
    `export DTOPEN_VPDF="${P.D32BIN}/d32read /usr/local/bin/mupdf"`,
    `export DTOPEN_VPS="/usr/local/bin/gv"`,
    '',
    '# GTK and Qt (DISTRO-DESIGN 3.6): the theme is chosen through xsettingsd, never GTK_THEME, so a palette',
    '# change in Style Manager can restyle running programs.',
    'export GTK_OVERLAY_SCROLLING=0',
    'export GTK_CSD=0',
    'export QT_QPA_PLATFORMTHEME=qt6ct',
    'export MOZ_GTK_TITLEBAR_DECORATION=system',
    '# Core X cursors everywhere (CDE-SPEC 4.6): no cursor theme.',
    'unset XCURSOR_THEME',
    '',
  ].join('\n');
}
function xsettingsStart(d) {
  return [
    '# ' + HDR(d, 'GTK settings daemon start'),
    '# Sourced by Xsession (ksh). Starts xsettingsd with the build-time theme of the session palette until the',
    '# palette follower (REPLAN B11) takes this over. Does nothing if xsettingsd is absent or already running.',
    'if [ -x /usr/local/bin/xsettingsd ] && ! pgrep -U "$(id -u)" -x xsettingsd >/dev/null 2>&1; then',
    '  /usr/local/bin/xsettingsd -c /usr/local/share/d32/theme/xsettingsd.conf >/dev/null 2>&1 &',
    'fi',
    '',
  ].join('\n');
}
function copyright(d) {
  const I = d.identity;
  return [
    `${I.os} Release ${d.release}`,
    `Copyright (C) ${I.year} ${I.maker}`,
    `${I.contact}`,
    'Licence: AGPL-3.0-or-later (code), CC-BY-4.0 (documents), CC BY-NC 4.0 (art).',
    '',
    `Third-party notices: ${I.notices}`,
    '',
    ...I.noticeLines,
    '',
  ].join('\n');
}

module.exports = { dp, sysResources, backdropLines, wsColourLines, profileRes, dtwmrc, greeter, GREETER_FILE, hello, env, xsettingsStart, copyright, HDR };
