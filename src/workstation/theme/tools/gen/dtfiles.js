function dtFile(d, release, file) {
  const P = d.paths;
  const out = [header(Object.assign({}, d, { release }), file.replace(/\.dt$/, '') + ' actions and data types')];
  out.push('# Paths, as DtDb variables (variables do not carry across files)');
  for (const [k, v] of Object.entries(P)) out.push(`set ${k}=${v}`);
  out.push('');
  const types = d.datatypes.filter(t => t.file === file && due(t.train, release));
  if (types.length) out.push('#' + '-'.repeat(110), '# Data types');
  for (const t of types) {
    out.push(rec('DATA_ATTRIBUTES', t.name, [
      kv('ACTIONS', t.actions.split(',').filter(a => a === 'Open' || d.actions.some(x => x.name === a && due(x.train, release))).join(',')),
      kv('ICON', t.icon),
      t.mime && kv('MIME_TYPE', t.mime),
      kv('DESCRIPTION', t.desc),
    ]));
    t.criteria.forEach((c, k) => out.push(rec('DATA_CRITERIA', `${t.name}${k + 1}`, [
      kv('DATA_ATTRIBUTES_NAME', t.name),
      c.name && kv('NAME_PATTERN', c.name),
      c.path && kv('PATH_PATTERN', c.path),
      c.content && kv('CONTENT', c.content),
      c.mode && kv('MODE', c.mode),
    ])));
  }
  const acts = d.actions.filter(a => a.file === file && due(a.train, release));
  const maps = d.openMaps.filter(m => m.file === file && due(m.train, release) && d.actions.some(a => a.name === m.to && due(a.train, release)));
  if (acts.length || maps.length) out.push('#' + '-'.repeat(110), '# Actions');
  for (const a of acts) {
    out.push(`# runs: ${a.owner}`);
    out.push(rec('ACTION', a.name, [
      kv('LABEL', a.label),
      a.icon && kv('ICON', a.icon),
      a.argType && kv('ARG_TYPE', a.argType),
      kv('TYPE', a.type),
      kv('WINDOW_TYPE', a.window),
      kv('EXEC_HOST', '%LocalHost%'),
      kv('EXEC_STRING', a.exec),
      kv('DESCRIPTION', a.desc),
    ]));
  }
  for (const m of maps) {
    out.push(`# Open on ${m.argType} goes to ${m.to}`);
    out.push(rec('ACTION', 'Open', [kv('ARG_TYPE', m.argType), kv('TYPE', 'MAP'), kv('MAP_ACTION', m.to)]));
  }
  if (file === APPGROUP_FILE) out.push(appGroupTypes(d, release));
  return out.join('\n');
}
const DT_FILES = ['deep32.dt', 'deep32-apps.dt', 'deep32-trays.dt', 'library.dt', 'fathom.dt'];

// ---------------------------------------------------------------------------------------------------------------
// Application Manager (DISTRO 6.8 fid 16, APPS 4.1, EP9). appManager() gives the groups due at a release:
// { Group: [action, ...] }: the package entries a group keeps (dtappgather does not merge groups of one name, so a
// group we ship replaces the package's whole) and our entries whose action is due. One action file per entry.
function appManager(d, release) {
  const actionDue = name => d.actions.some(a => a.name === name && due(a.train, release));
  const groups = {};
  for (const g of d.appmanager.groups) {
    const ours = g.entries.filter(actionDue);
    // a stock group is only shipped (and so replaced) when it carries something of ours
    if (!ours.length && (g.stock || !(g.keep || []).length)) continue;
    groups[g.name] = [...(g.keep || []), ...ours].sort();
  }
  return groups;
}
// The action file: the package's entries carry a comment and an echo; this is the same idea in our words.
const ACTION_FILE = [
  '# Deep32/UX Application Manager entry (d32-theme). The File Manager treats an executable file whose name matches',
  '# an action as that action, so this file opens the action of the same name. Its contents do not matter.',
  'echo "This is a desktop action. Open it from the Application Manager."', ''].join('\n');
// The data types of the groups the package does not have, as the package's dtappman.dt does for its own groups:
// the group's icon in Application Manager, Open and Print mapped to the stock app-group actions.
const APPGROUP_FILE = 'deep32.dt';
function appGroupTypes(d, release) {
  const live = appManager(d, release);
  const out = [];
  const groups = d.appmanager.groups.filter(g => !g.stock && live[g.name]);
  if (!groups.length) return '';
  out.push('#' + '-'.repeat(110), '# Application Manager groups of our own (the stock groups have theirs in dtappman.dt)');
  for (const g of groups) {
    const t = `D32_APPGROUP_${g.name}`;
    out.push(rec('DATA_ATTRIBUTES', t, [kv('ACTIONS', 'OpenInPlace,OpenNewView,Print'), kv('ICON', g.icon), kv('LABEL', g.name),
      kv('MEDIA', 'FILE_NAME'), kv('MOVE_TO_ACTION', 'FILESYSTEM_MOVE'), kv('COPY_TO_ACTION', 'FILESYSTEM_COPY'),
      kv('LINK_TO_ACTION', 'FILESYSTEM_LINK'), kv('DESCRIPTION', `Double-click this icon to open the ${g.name} application group.`),
      kv('TYPE_LABEL', 'D32_APPGROUP')]));
    out.push(rec('DATA_CRITERIA', `${t}1`, [kv('DATA_ATTRIBUTES_NAME', t), kv('MODE', 'd'), kv('PATH_PATTERN', `*/appmanager/*/${g.name}`)]));
    out.push(rec('ACTION', 'Open', [kv('LABEL', 'Open'), kv('ARG_TYPE', t), kv('TYPE', 'MAP'), kv('MAP_ACTION', 'OpenAppGroup')]));
    out.push(rec('ACTION', 'Print', [kv('LABEL', 'Print'), kv('ARG_TYPE', t), kv('TYPE', 'MAP'), kv('MAP_ACTION', 'PrintAppGroup')]));
  }
  return out.join('\n');
}

module.exports = { frontPanel, panelGeometry, dtFile, DT_FILES, appManager, ACTION_FILE };
