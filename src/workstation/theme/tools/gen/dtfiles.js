'use strict';
// The front panel (deep32.fp) and the action and data-type files (*.dt), in CDE's Dt database syntax
// (dtwm.fp.src, dtpad.dt.src). Records are gated by train so a release never shows a control it cannot run.
const { due, form } = require('./common');

// Stock main-panel controls that every release keeps, so their subpanels always have a parent.
const STOCK_PARENTS = ['Style', 'Applications', 'TextEditor'];

const kv = (k, v) => `  ${k.padEnd(20)} ${v}`;
const rec = (type, name, fields) => [`${type} ${name}`, '{', ...fields.filter(Boolean), '}', ''].join('\n');

function header(d, what) {
  return [
    `# Deep32/UX ${d.release === 'all' ? 'D.32.x (all trains)' : d.release} ${what} (d32-theme).`,
    '# Generated by tools/gen.js from src/theme-data.js; Dt database syntax as CDE 2.5 (dtdtfile(4), dtfpfile(4)).',
    '# Lives in /etc/dt/appconfig/types/C, which is read before the package directory: for records with the same',
    '# name the first one read wins, so a record here overrides the stock one (dtwm DataBaseLoad.c).',
    'set DtDbVersion=1.0',
    '',
  ].join('\n');
}

// ---------------------------------------------------------------------------------------------------------------
// problems: optional array; a due control that cannot be placed is reported there (gen.js fails on it, and
// validate.js T-DT-4 checks the output independently), never dropped silently.
function frontPanel(d, release, problems = []) {
  const FP = d.frontpanel;
  const out = [header(Object.assign({}, d, { release }), 'front panel')];
  const control = (c, container, ctype) => rec('CONTROL', c.name, [
    kv('TYPE', c.type),
    kv('CONTAINER_NAME', container),
    kv('CONTAINER_TYPE', ctype),
    kv('POSITION_HINTS', String(c.pos)),
    c.icon && kv('ICON', c.icon),
    c.alt && kv('ALTERNATE_ICON', c.alt),
    c.monitor && kv('MONITOR_TYPE', c.monitor),
    c.fileName && kv('FILE_NAME', c.fileName),
    c.label && kv('LABEL', c.label),
    c.push && kv('PUSH_ACTION', c.push),
    c.recall && kv('PUSH_RECALL', 'True'),
    c.client && kv('CLIENT_NAME', c.client),
    c.drop && kv('DROP_ACTION', c.drop),
    ...Object.entries(c.extra || {}).map(([k, v]) => kv(k, v)),
    c.help && kv('HELP_STRING', c.help),
    c.helpTopic && kv('HELP_TOPIC', c.helpTopic),
    c.helpVolume && kv('HELP_VOLUME', c.helpVolume),
  ]);
  out.push('#' + '-'.repeat(110));
  out.push('# Stock controls removed. DELETE matches the stock record by name, container and TYPE (EliminateDeleted).');
  for (const s of FP.stockDeletes) {
    out.push(`# ${s.why}`);
    out.push(rec('CONTROL', s.name, [kv('TYPE', s.type), kv('CONTAINER_NAME', s.container), kv('CONTAINER_TYPE', s.ctype), kv('DELETE', 'True')]));
  }
  out.push('#' + '-'.repeat(110));
  out.push('# Main panel (Top box). Positions are CDE\'s 13 cells; the switch stays at 7 (DISTRO-DESIGN 6.4).');
  const subpanelsDue = new Set();
  for (const c0 of FP.main) {
    const c = form(c0, release);
    if (due(c.train, release)) {
      out.push(control(c, 'Top', 'BOX'));
      if (c.subpanel) subpanelsDue.add(c.subpanel);
    } else {
      // keep the silhouette until the control's train arrives. The stock Fpblank is a 6x48 spacer (the VM proof:
      // stock CDE draws positions 6 and 8 as narrow gaps beside the switch), so positions 6 and 8 keep that stock
      // spacer, and a position that holds a full control in stock CDE (5 Mail, 9 Printer) gets D32blank, an empty
      // 48x48 cell, so First light shows the stock panel's silhouette exactly.
      const spacer = [6, 8].includes(c.pos) ? 'Fpblank' : 'D32blank';
      out.push(`# ${c.label} arrives in ${c.train}; a blank cell (${spacer}) holds position ${c.pos} until then.`);
      out.push(rec('CONTROL', 'D32Blank' + c.pos, [kv('TYPE', 'blank'), kv('CONTAINER_NAME', 'Top'), kv('CONTAINER_TYPE', 'BOX'),
        kv('POSITION_HINTS', String(c.pos)), kv('ICON', spacer), kv('HELP_TOPIC', 'FPOnItemFrontPanel'), kv('HELP_VOLUME', 'FPanel')]));
    }
  }
  out.push('#' + '-'.repeat(110));
  out.push('# Subpanels');
  for (const sp0 of FP.subpanels) {
    const sp = form(sp0, release);
    // omit: controls left out of this form of the subpanel. dtwm copies the main-panel control into its subpanel
    // (the VM renders show it at the top), so an entry that would repeat the main control is left out.
    const ctls = sp.controls.filter(c => due(c.train, release) && !(sp.omit || []).includes(c.name));
    if (!ctls.length) continue;
    const parentDue = sp.stock || STOCK_PARENTS.includes(sp.container) || subpanelsDue.has(sp.name);
    if (!parentDue || !due(sp.train, release)) {
      problems.push(`${release}: subpanel ${sp.name} is not emitted (${!parentDue ? `its control ${sp.container} is not on the panel` :
        `its train is ${sp.train}`}), so the due control(s) ${ctls.map(c => c.name).join(', ')} would have no way in`);
      continue;
    }
    if (!sp.stock) out.push(rec('SUBPANEL', sp.name, [kv('CONTAINER_NAME', sp.container), kv('TITLE', sp.title)]));
    else out.push(`# ${sp.title}: the stock subpanel of ${sp.container}, extended`);
    // keep positions dense and in the designed order
    ctls.forEach((c, k) => out.push(control(Object.assign({}, c, { pos: k + 1 }), sp.name, 'SUBPANEL')));
  }
  return out.join('\n');
}

// Geometry fragments for d32-display (ISO 9.2.3): dtwm centres the panel on the whole X screen, so on the docked
// layout the panel is placed on the 34" head. Installed by d32-display in ~/.dt/types (read before /etc).
function panelGeometry(d, x, note) {
  return [
    `# Deep32/UX front panel placement: ${note} (d32-theme; installed by d32-display into ~/.dt/types/).`,
    'set DtDbVersion=1.0', '',
    rec('PANEL', 'FrontPanel', [kv('PANEL_GEOMETRY', x), kv('DISPLAY_HANDLES', 'True'), kv('DISPLAY_MENU', 'True'),
      kv('DISPLAY_MINIMIZE', 'True'), kv('CONTROL_BEHAVIOR', 'single_click'), kv('DISPLAY_CONTROL_LABELS', 'False'),
      kv('HELP_TOPIC', 'FPOnItemFrontPanel'), kv('HELP_VOLUME', 'FPanel')]),
  ].join('\n');
}

