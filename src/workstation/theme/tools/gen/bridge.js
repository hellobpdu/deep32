// The theme bridge (DISTRO-DESIGN 3.6 and 6.12, LOOK-SOUND 9.4): GTK 3, GTK 2, Qt and Xt clients matched to the
// CDE palette, the look profile's bevel thickness and the Deep32 bitmap faces. One theme per stock palette and
// colour use, named Deep32-CDE-<Palette>-<HIGH|MEDIUM>, selected at run time through xsettingsd (never GTK_THEME).
// Motif rules carried over: solid colours, bevels as per-side border colours, no rounded corners, no animation,
// no gradients or shadows; selection drawn inverted as Motif draws selected text (CDE-SPEC 2.3.6).
const { Canvas } = require('../lib/canvas');
const png = require('../lib/png');

function roles(s) {
  // s = paletteSets(...) for one colour use
  return {
    win: s[5], menu: s[6], text: s[4], focus: s[1], inactive: s[2],
  };
}

// ---- indicator and arrow assets (13x13, per palette and profile) -------------------------------------------
function assets(s, prof) {
  const R = roles(s); const out = {};
  const mk = (draw) => { const c = new Canvas(13, 13, R.win.bg); draw(c); return png.encode(c); };
  const t = prof.thickness;
  out['check-off.png'] = mk(c => { c.raised(0, 0, 13, 13, t, R.win); });
  out['check-on.png'] = mk(c => {
    if (prof.check === 'filled') { c.sunken(0, 0, 13, 13, t, R.win); c.fill(t, t, 13 - 2 * t, 13 - 2 * t, R.win.sc); }
    else { c.sunken(0, 0, 13, 13, 1, R.win); c.fill(1, 1, 11, 11, R.win.sc); c.check(2, 2, 9, R.win.fg); }
  });
  out['radio-off.png'] = mk(c => { if (prof.radio === 'diamond') c.diamond(0, 0, 13, t, R.win, false); else c.circle(0, 0, 13, R.win, false); });
  out['radio-on.png'] = mk(c => { if (prof.radio === 'diamond') c.diamond(0, 0, 13, t, R.win, true); else c.circle(0, 0, 13, R.win, true, R.focus.bg); });
  for (const d of ['up', 'down', 'left', 'right']) out[`arrow-${d}.png`] = (() => { const c = new Canvas(11, 11, R.win.sc); c.arrow(0, 0, 11, d, R.win); return png.encode(c); })();
  return out;
}

