// ---- Xt class resources (never a bare *background, DISTRO-DESIGN 3.6) ---------------------------------------
function xt(name, s) {
  const R = roles(s);
  const L = [`! ${name}: class resources for Xt, Xaw and Tk programs (d32-theme). Merged with xrdb -merge.`];
  const put = (k, v) => L.push(`${k}:`.padEnd(30) + v);
  for (const c of ['XTerm', 'UXTerm']) { put(`${c}*background`, R.text.bg); put(`${c}*foreground`, R.text.fg); put(`${c}*cursorColor`, R.text.fg);
    put(`${c}*scrollBar`, 'true'); put(`${c}*font`, '-dt-interface user-medium-r-normal-m*-*-*-*-*-*-*-*-*'); }
  for (const c of ['XClock', 'XLoad', 'XCalc', 'XEyes', 'Xmag', 'XBiff']) { put(`${c}*background`, R.win.bg); put(`${c}*foreground`, R.win.fg); }
  put('XClock*hands', R.win.fg); put('XClock*highlight', R.win.bs); put('XLoad*highlight', R.win.bs);
  put('Xfig*background', R.win.bg); put('Xfig*foreground', R.win.fg);
  put('Xfig*Text*background', R.text.bg); put('Xfig*Text*foreground', R.text.fg);
  return L.join('\n') + '\n';
}

function indexTheme(name, pal, use, prof) {
  return `[Desktop Entry]\nType=X-GNOME-Metatheme\nName=${name}\nComment=CDE palette ${pal}, ${use}, ${prof.shownAs} (Deep32/UX)\nEncoding=UTF-8\n\n[X-GNOME-Metatheme]\nGtkTheme=${name}\nIconTheme=Deep32-CDE\n`;
}

