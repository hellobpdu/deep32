const QT_ROLES = ['WindowText', 'Button', 'Light', 'Midlight', 'Dark', 'Mid', 'Text', 'BrightText', 'ButtonText', 'Base',
  'Window', 'Shadow', 'Highlight', 'HighlightedText', 'Link', 'LinkVisited', 'AlternateBase', 'NoRole', 'ToolTipBase',
  'ToolTipText', 'PlaceholderText'];
function qtColours(name, s) {
  const R = roles(s);
  const argb = h => '#ff' + h.slice(1).toLowerCase();
  const base = { WindowText: R.win.fg, Button: R.win.bg, Light: R.win.ts, Midlight: R.win.ts, Dark: R.win.bs, Mid: R.win.sc,
    Text: R.text.fg, BrightText: '#FFFFFF', ButtonText: R.win.fg, Base: R.text.bg, Window: R.win.bg, Shadow: R.win.bs,
    Highlight: R.text.fg, HighlightedText: R.text.bg, Link: R.text.fg, LinkVisited: R.text.fg, AlternateBase: R.text.bg,
    NoRole: '#000000', ToolTipBase: R.menu.bg, ToolTipText: R.menu.fg, PlaceholderText: R.text.sc };
  const dis = Object.assign({}, base, { WindowText: R.win.bs, Text: R.text.sc, ButtonText: R.win.bs });
  const row = m => QT_ROLES.map(k => argb(m[k])).join(', ');
  return `# ${name}: qt5ct/qt6ct colour scheme generated by Deep32/UX tools/gen.js (d32-theme).\n[ColorScheme]\nactive_colors=${row(base)}\ndisabled_colors=${row(dis)}\ninactive_colors=${row(base)}\n`;
}
