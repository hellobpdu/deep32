def rewrite_line(entry: Entry, name: str, old: bytes, new: bytes) -> bytes:
    lines = entry.content.read_bytes().split(b"\n")
    hits = [i for i, line in enumerate(lines) if line == old]
    if len(hits) != 1:
        raise Refusal(f"{name}: expected one line {old.decode('utf-8', 'replace')!r}, found {len(hits)}")
    lines[hits[0]] = new
    return b"\n".join(lines)


def rewrite_ledger_row(entry: Entry, installed: str, before: str, after: str) -> bytes:
    lines = entry.content.read_bytes().split(b"\n")
    header = lines[0].decode("utf-8").split("\t")
    needed = ("installed_path", "sha256", "origin", "source", *ASSET_LEDGER_ROW)
    if any(column not in header for column in needed) or len(set(header)) != len(header):
        raise Refusal("assets/LEDGER-v2.tsv: header lacks a column the asset copy rewrite needs")
    rows = []
    for index, line in enumerate(lines[1:], 1):
        if not line or line.startswith(b"#"):
            continue
        cells = line.decode("utf-8").split("\t")
        if len(cells) != len(header):
            raise Refusal(f"assets/LEDGER-v2.tsv line {index + 1}: {len(cells)} columns, header has {len(header)}")
        row = dict(zip(header, cells))
        if row["installed_path"] == installed and not row["origin"].startswith("HELD"):
            rows.append((index, row))
    if len(rows) != 1 or rows[0][1]["sha256"] != before:
        raise Refusal(f"assets/LEDGER-v2.tsv: expected one live row for {installed} with the alpha.1 hash")
    index, row = rows[0]
    row.update(ASSET_LEDGER_ROW, sha256=after, source="public:theme:root" + installed)
    lines[index] = "\t".join(row[column] for column in header).encode("utf-8")
    return b"\n".join(lines)


def regenerate_theme(result: dict[str, Entry], scratch: Path, node, changes: list[dict]) -> None:
    """Run the theme generator on the final tree's theme sources and take its output (see THEME_REGENERATED)."""
    old = {name: entry for name, entry in result.items() if name.startswith(THEME_OUT)}
    if not old:
        return
    if node is None:
        raise Refusal("the tree carries generated theme output (theme/out/all): give --node to regenerate it "
                      "from the merged theme sources")
    inputs = {name[len("theme/"):]: entry for name, entry in result.items()
              if name.startswith("theme/") and not name.startswith("theme/out/")}
    if "tools/gen.js" not in inputs:
        raise Refusal("the tree carries theme output but no theme/tools/gen.js")
    work = scratch / "theme-generate"
    # The only place archive and commit names reach the filesystem: theme sources (already checked portable and
    # collision-free) written below a new scratch folder for the generator.
    for rel, entry in sorted(inputs.items()):
        target = work.joinpath(*rel.split("/"))
        target.parent.mkdir(parents=True, exist_ok=True)
        with entry.content.open("rb") as stream, target.open("xb") as out:
            while chunk := stream.read(1024 * 1024):
                out.write(chunk)
    result_run = subprocess.run([str(node), *THEME_GENERATOR], cwd=work, env=generator_env(),
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if result_run.returncode:
        tail = result_run.stdout.decode("utf-8", "replace").strip().splitlines()[-5:]
        raise Refusal(f"theme generator failed (exit {result_run.returncode}): " + " | ".join(tail))
    produced = tree_files(work)
    for rel, entry in inputs.items():
        if rel not in produced or hashlib.sha256(produced[rel].read_bytes()).hexdigest() != entry.digest:
            raise Refusal("theme generator changed or removed a source: theme/" + rel)
    outside = sorted(rel for rel in produced if rel not in inputs and not ("theme/" + rel).startswith(THEME_OUT))
    if outside:
        raise Refusal("theme generator wrote outside theme/out/all: " + ", ".join("theme/" + rel for rel in outside))
    new = {"theme/" + rel: path for rel, path in produced.items() if ("theme/" + rel).startswith(THEME_OUT)}
    if set(new) != set(old):
        added, dropped = sorted(set(new) - set(old)), sorted(set(old) - set(new))
        raise Refusal("regenerated theme output adds or drops files: added " + ", ".join(added[:5]) +
                      "; dropped " + ", ".join(dropped[:5]))
    regenerated = {}
    for index, name in enumerate(sorted(new)):
        with new[name].open("rb") as stream:
            entry = spool(stream, scratch / f"theme-{index}", old[name].mode)
        if entry.digest != old[name].digest:
            regenerated[name] = entry
    unexpected = sorted(set(regenerated) - THEME_REGENERATED)
    if unexpected:
        # The PNGs depend on Node's zlib: alpha.1's were made by an official Node.js build (bundled zlib).
        raise Refusal(f"regenerated theme output differs outside the expected paths ({len(unexpected)} files; "
                      "PNG differences mean this Node.js's zlib is not the one that made alpha.1): " +
                      ", ".join(unexpected[:10]))
    identity = subprocess.run([str(node), "-p", "process.version + ' zlib ' + process.versions.zlib"],
                              env=generator_env(), stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    version = identity.stdout.decode("ascii", "replace").strip() or "version unknown"
    generator = "theme/" + " ".join(THEME_GENERATOR) + " (node " + version + ")"
    for name, entry in sorted(regenerated.items()):
        changes.append({**change_row(name, "theme-regenerated", old[name].digest, entry.digest), "source": generator})
        result[name] = entry
    for index, rel in enumerate(THEME_ASSET_COPIES):
        theme_name, asset_name = THEME_OUT + "root/" + rel, "assets/root/" + rel
        if theme_name not in regenerated or asset_name not in result:
            continue
        before, after = old[theme_name].digest, regenerated[theme_name].digest
        if result[asset_name].digest != before:
            raise Refusal(f"{asset_name}: the asset copy does not mirror the alpha.1 theme output")
        for name in ("assets/SHA256SUMS", "assets/LEDGER-v2.tsv"):
            if name not in result:
                raise Refusal(f"the tree has {asset_name} but no {name}")
        sums = rewrite_line(result["assets/SHA256SUMS"], "assets/SHA256SUMS",
                            f"{before}  {rel}".encode("utf-8"), f"{after}  {rel}".encode("utf-8"))
        ledger = rewrite_ledger_row(result["assets/LEDGER-v2.tsv"], "/" + rel, before, after)
        for name, data in ((asset_name, None), ("assets/SHA256SUMS", sums), ("assets/LEDGER-v2.tsv", ledger)):
            old_entry = result[name]
            if data is None:
                with regenerated[theme_name].content.open("rb") as stream:
                    entry = spool(stream, scratch / f"asset-{index}-copy", old_entry.mode)
            else:
                entry = spool(io.BytesIO(data), scratch / f"asset-{index}-{posixpath.basename(name)}", old_entry.mode)
            changes.append(change_row(name, "theme-asset-copy", old_entry.digest, entry.digest))
            result[name] = entry


def overlay(files: dict[str, Entry], source: GitSource, scratch: Path, *,
            deletions=None, node=None) -> tuple[dict[str, Entry], list[dict]]:
    pin = {name: entry.digest for name, entry in files.items()}
    _, after, changes, contents, names, _, conflicts, deletions = correspondence(
        source, pin, deletions=deletions)
    if conflicts:
        raise Conflicts(conflicts)
    result = {name: entry for name, entry in files.items() if name not in deletions}
    for index, name in enumerate(sorted(after)):
        row = after[name]
        result[name] = spool(io.BytesIO(contents[name]), scratch / f"overlay-{index}", row["mode"])
    # Lead 2026-11-17: surviving alpha.1-only files (e.g. the unpublished Library C tests) that include a renamed
    # header get the published name, so they still compile; every rewrite is recorded in the change report.
    include = re.compile(rb'(#[ \t]*include[ \t]*")([^"\r\n]+)(")')
    for index, name in enumerate(sorted(n for n in result if n not in after)):
        entry = result[name]
        data = entry.content.read_bytes()
        if b"include" not in data:
            continue
        def rewrite(match, base=posixpath.dirname(name)):
            target = posixpath.normpath(posixpath.join(base, match.group(2).decode("utf-8", "replace")))
            new = D1_FC_HEADER_RENAMES.get(target)
            if new is None:
                return match.group(0)
            reference = match.group(2).decode("utf-8")
            return match.group(1) + (reference[: -len(posixpath.basename(target))] + posixpath.basename(new)).encode("utf-8") + match.group(3)
        updated = include.sub(rewrite, data)
        if updated != data:
            old_digest = entry.digest
            result[name] = spool(io.BytesIO(updated), scratch / f"rename-{index}", entry.mode)
            changes.append({"path": name, "source": None, "action": "include-rename",
                            "alpha1_sha256": old_digest, "published_sha256": None,
                            "merged_sha256": result[name].digest, "before_sha256": old_digest,
                            "after_sha256": result[name].digest})
    for index, (name, pairs) in enumerate(sorted(D1_FC_RELAY_PORT_LINES.items())):
        if name in after or name not in result:
            continue
        entry = result[name]
        lines = entry.content.read_bytes().split(b"\n")
        for old, new in pairs:
            hits = [i for i, line in enumerate(lines) if line == old]
            if len(hits) != 1:
                raise Refusal(f"relay port rewrite expected one line in {name}, found {len(hits)}")
            lines[hits[0]] = new
        updated = b"\n".join(lines)
        old_digest = entry.digest
        result[name] = spool(io.BytesIO(updated), scratch / f"relay-port-{index}", entry.mode)
        changes.append({"path": name, "source": None, "action": "relay-port-7452",
                        "alpha1_sha256": old_digest, "published_sha256": None,
                        "merged_sha256": result[name].digest, "before_sha256": old_digest,
                        "after_sha256": result[name].digest})
    regenerate_theme(result, scratch, node, changes)
    conflicts = reference_conflicts({name: entry.content for name, entry in result.items()},
                                    names, source, after, deletions)
    if conflicts:
        raise Conflicts(conflicts)
    check_names(result)
    return result, changes


def write_tar(destination: Path, files: dict[str, Entry], directories: dict[str, int]) -> None:
    # Fixed metadata, ordering and PAX format make bytes independent of source
    # archive ordering, timestamp, ownership, scratch directory and platform.
    with tarfile.open(destination, "w", format=tarfile.PAX_FORMAT, encoding="utf-8") as output:
        for name in sorted(set(files) | set(directories)):
            info = tarfile.TarInfo(name)
            info.mtime = 0
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            if name in directories:
                info.type = tarfile.DIRTYPE
                info.mode = directories[name]
                output.addfile(info)
            else:
                entry = files[name]
                info.mode, info.size = entry.mode, entry.size
                with entry.content.open("rb") as stream:
                    output.addfile(info, stream)


def write_json(path: Path, value: dict) -> None:
    path.write_bytes((json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n").encode("ascii"))


def build(alpha1_tar: Path, alpha1_pin: Path, source: GitSource, output_dir: Path, *,
          deletions=None, node=None) -> dict:
    if output_dir.exists() or output_dir.is_symlink():
        raise Refusal("output directory must not already exist")
    if not output_dir.parent.is_dir():
        raise Refusal("output directory parent does not exist")
    pin_data = alpha1_pin.read_bytes()
    pin = parse_pin(pin_data)
    # Temporary storage has generated flat names, never archive-provided names.
    with tempfile.TemporaryDirectory(prefix="alpha2-tree-", dir=output_dir.parent) as temporary:
        scratch = Path(temporary)
        files, directories = read_alpha1(alpha1_tar, pin, scratch)
        files, changes = overlay(files, source, scratch, deletions=deletions, node=node)
        check_layout(files, directories)
        new_pin = pin_bytes({name: entry.digest for name, entry in files.items()})
        tree_hash = hashlib.sha256(new_pin).hexdigest()
        staged = scratch / "output"
        staged.mkdir()
        archive_name = f"tree-{tree_hash}.tar"
        write_tar(staged / archive_name, files, directories)
        (staged / "PIN.sha256").write_bytes(new_pin)
        (staged / "TREE-HASH").write_bytes((tree_hash + "\n").encode("ascii"))
        (staged / "build.conf.patch").write_bytes((
            "--- build.conf\n+++ build.conf\n@@ -1 +1 @@\n"
            "-D32_RELEASE_ID=0.1.0-alpha.1\n"
            f"+D32_RELEASE_ID={RELEASE_ID}\n@@ -3 +3 @@\n"
            f"-D32_TREE_HASH={hashlib.sha256(pin_data).hexdigest()}\n"
            f"+D32_TREE_HASH={tree_hash}\n").encode("ascii"))
        # This exact two-variable fragment can be appended to a backed-up config;
        # it deliberately contains no host-specific or signing configuration.
        (staged / "build.conf.alpha2").write_bytes((
            f"D32_RELEASE_ID={RELEASE_ID}\nD32_TREE_HASH={tree_hash}\n").encode("ascii"))
        report = {"format": "deep32-alpha2-tree-v1", "published_commit": source.published,
                  "source_commit": source.commit, "release_id": RELEASE_ID,
                  "alpha1_pin_sha256": hashlib.sha256(pin_data).hexdigest(),
                  "tree_hash": tree_hash, "tree_archive": archive_name,
                  "files": len(files), "directories": len(directories), "changes": changes, "conflicts": [],
                  "archive_verified": True, "reference_scope": "final-tree",
                  "counts": {"replaced": sum(r["action"] == "replace" for r in changes),
                             "added": sum(r["action"] == "add" for r in changes),
                             "deleted": sum(r["action"] == "delete" for r in changes),
                             "kept": len(pin) - sum(r["action"] in ("replace", "delete") for r in changes)}}
        write_json(staged / "change-report.json", report)
        # Destination is new; refuse overwrite, including symlinks. rename is on
        # the same filesystem and publishes only fully verified outputs.
        if output_dir.exists() or output_dir.is_symlink():
            raise Refusal("output directory appeared during build")
        staged.rename(output_dir)
    return report


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--alpha1-tar", type=Path)
    parser.add_argument("--alpha1-pin", type=Path, required=True)
    parser.add_argument("--checkout", type=Path, required=True)
    parser.add_argument("--commit", required=True)
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--audit-pin-only", action="store_true")
    parser.add_argument("--node", type=Path,
                        help="Node.js for the theme generator (required when the alpha.1 tree carries theme/out)")
    parser.add_argument("--deletions", type=Path,
                        default=Path(__file__).with_name("alpha1-deletions.sha256"))
    args = parser.parse_args(argv)
    try:
        deletions = deletion_table(args.deletions.read_bytes())
        source = GitSource(args.checkout, args.commit)
        if args.audit_pin_only:
            report = audit_pin(source, parse_pin(args.alpha1_pin.read_bytes()), require_diagnostics=False, deletions=deletions)
            print(json.dumps(report, indent=2, sort_keys=True))
            return 2 if report["conflicts"] else 0
        if args.alpha1_tar is None or args.output_dir is None:
            parser.error("a build requires --alpha1-tar and --output-dir")
        report = build(args.alpha1_tar, args.alpha1_pin, source, args.output_dir, deletions=deletions, node=args.node)
        print(report["tree_hash"])
        return 0
    except (Refusal, OSError, tarfile.TarError, UnicodeError) as exc:
        print(f"REFUSED: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
